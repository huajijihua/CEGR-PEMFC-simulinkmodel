    focused.commonBackpressureValveKi_area_per_MPa_s, "external_case_default");
mapping(end + 1) = mappedEntry( ...
    'focused.commonBackpressureValveKi_area_per_MPa_s', source, ...
    'common_bp_valve_control_Ki_area_per_MPa_s', ...
    focused.commonBackpressureValveKi_area_per_MPa_s, 'm^2/(MPa*s)', 'mapped');

if isfield(caseCfg, 'cathode') && isstruct(caseCfg.cathode) && ...
        isfield(caseCfg.cathode, 'freshAirWaterMoleFraction')
    mapping(end + 1) = mappedEntry( ...
        'environment.ambientRelativeHumidity', ...
        'derived_from_environment_T_p_RH', 'env_yH20', ...
        caseCfg.cathode.freshAirWaterMoleFraction, 'mole fraction', ...
        'derived');
end

[focused.cathodeSourceTemperature_C, source] = selectValue(caseCfg, ...
    'cathodeSourceTemperature_C', ...
    {{'cathode', 'sourceTemperature_C'}}, ...
    focused.cathodeSourceTemperature_C, "platform_default");
