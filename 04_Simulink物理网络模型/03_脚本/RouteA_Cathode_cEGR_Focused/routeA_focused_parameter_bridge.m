validateRange(focused.cathodeSourcePressure_MPa_abs, [0.05, 1], ...
    'focused.cathodeSourcePressure_MPa_abs');
validateRange(focused.cathodeSourceTemperature_C, [-50, 150], ...
    'focused.cathodeSourceTemperature_C');
validateRange(focused.cathodeChannelDpNominal_MPa, [1e-5, 0.2], ...
    'focused.cathodeChannelDpNominal_MPa');
