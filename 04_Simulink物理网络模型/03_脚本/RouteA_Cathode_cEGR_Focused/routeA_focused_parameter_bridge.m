function [value, source] = selectValue(caseCfg, focusedName, standardPaths, default, defaultSource)
if hasFocusedField(caseCfg, focusedName)
    value = caseCfg.focused.(focusedName);
    source = "focused." + string(focusedName);
else
    value = default;
    source = defaultSource;
    for idx = 1:numel(standardPaths)
        standardPath = standardPaths{idx};
        if hasNestedField(caseCfg, standardPath)
            value = getNestedField(caseCfg, standardPath);
            source = string(standardPath{1}) + "." + string(standardPath{2});
            break;
        end
    end
end
end

function [value, source] = selectFocusedOnly(caseCfg, fieldName, default, defaultSource)
if hasFocusedField(caseCfg, fieldName)
    value = caseCfg.focused.(fieldName);
    source = "focused." + string(fieldName);
else
    value = default;
    source = defaultSource;
end
end

function [value, source] = selectEjectorValue(caseCfg, fieldName, default, defaultSource)
focusedName = ['ejector', upper(fieldName(1)), fieldName(2:end)];
if isfield(caseCfg, 'ejector') && isstruct(caseCfg.ejector) && ...
        isfield(caseCfg.ejector, fieldName) && ...
        ~isempty(caseCfg.ejector.(fieldName))
    value = caseCfg.ejector.(fieldName);
    source = "ejector." + string(fieldName);
elseif hasFocusedField(caseCfg, focusedName)
    value = caseCfg.focused.(focusedName);
    source = "focused." + string(focusedName);
else
    value = default;
    source = defaultSource;
end
end

function present = hasFocusedField(caseCfg, fieldName)
present = isfield(caseCfg, 'focused') && isstruct(caseCfg.focused) && ...
    isfield(caseCfg.focused, fieldName) && ~isempty(caseCfg.focused.(fieldName));
end

function present = hasNestedField(s, path)
present = isfield(s, path{1}) && isstruct(s.(path{1})) && ...
    isfield(s.(path{1}), path{2}) && ~isempty(s.(path{1}).(path{2}));
end

function value = getNestedField(s, path)
value = s.(path{1}).(path{2});
end

function mapping = addNotApplicable(mapping, caseCfg, canonicalName, reason, text)
entry = mappedEntry(canonicalName, "case field if supplied", "", NaN, ...
    "", "not_applicable");
entry.reason = string(text);
entry.sourcePresent = hasCanonicalField(caseCfg, canonicalName);
entry.targetVariable = string(reason);
mapping(end + 1) = entry;
end

function present = hasCanonicalField(caseCfg, canonicalName)
parts = split(string(canonicalName), '.');
if string(canonicalName) == "anode.humidifierRH"
    canonicalName = "anode.humidifierRelativeHumidity";
    parts = split(canonicalName, '.');
end
value = caseCfg;
for idx = 1:numel(parts)
    if ~isstruct(value) || ~isfield(value, char(parts(idx)))
        present = false;
        return;
    end
    value = value.(char(parts(idx)));
end
present = ~isempty(value);
end

function entry = mappedEntry(canonicalName, sourcePath, targetVariable, value, unit, status)
entry = mappingTemplate();
entry.canonicalName = string(canonicalName);
entry.sourcePath = string(sourcePath);
entry.targetVariable = string(targetVariable);
entry.value = value;
entry.unit = string(unit);
entry.status = string(status);
entry.reason = "";
entry.sourcePresent = false;
end

function entry = mappingTemplate()
entry = struct( ...
    'canonicalName', "", ...
    'sourcePath', "", ...
    'targetVariable', "", ...
    'value', NaN, ...
    'unit', "", ...
    'status', "", ...
    'reason', "", ...
    'sourcePresent', false);
end

function validateFocusedValues(focused)
