function validateRange(value, bounds, name)
validateattributes(value, {'numeric'}, {'scalar', 'real', 'finite'}, ...
    'RouteA:FocusedBoundaryValue', name);
if value < bounds(1) || value > bounds(2)
    error('RouteA:FocusedBoundaryRange', ...
        '%s must be within [%.6g, %.6g].', name, bounds(1), bounds(2));
end
