    {'scalar', 'real', 'finite'}, 'RouteA:FocusedEjectorEnabled');
if ~ismember(double(focused.ejectorEnabled), [0, 1])
    error('RouteA:FocusedEjectorEnabled', ...
        'focused.ejectorEnabled must be false/true or 0/1.');
