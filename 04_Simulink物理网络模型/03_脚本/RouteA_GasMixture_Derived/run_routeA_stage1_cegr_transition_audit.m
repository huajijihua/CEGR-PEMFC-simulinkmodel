    stats.n2StackResidual_kg_s, stats.o2FaradayResidual_kg_s, ...
    stats.n2MixResidual_kg_s, stats.o2MixResidual_kg_s, ...
    stats.outletFlowClosure_kg_s]));
stats.passed = stats.finite && stats.n2StackPassed && ...
    stats.o2FaradayPassed && stats.n2MixPassed && stats.o2MixPassed;
end

