function text = formatNonfiniteCounts(counts)
names = fieldnames(counts);
parts = cell(1, numel(names));
for idx = 1:numel(names)
    parts{idx} = sprintf('%s=%d', names{idx}, counts.(names{idx}));
end
text = strjoin(parts, ', ');
end

function resetModelFromDisk(model, modelFile)
if bdIsLoaded(model)
    close_system(model, 0);
end
load_system(modelFile);
end

function refreshModelWorkspace(model)
mw = get_param(model, 'ModelWorkspace');
if strcmp(mw.DataSource, 'MATLAB File')
    mw.reload;
end
end
