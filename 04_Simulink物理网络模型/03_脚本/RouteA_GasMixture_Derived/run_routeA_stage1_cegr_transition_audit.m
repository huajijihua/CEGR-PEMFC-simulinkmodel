timing.fall10ResearchTime_s = fall10 - cfg.researchStartTime_s;
end

function crossing = firstCrossingTime(time, values, threshold, direction)
if strcmp(direction, 'up')
    idx = find(values >= threshold, 1, 'first');
else
    idx = find(values <= threshold, 1, 'first');
end
if isempty(idx)
    crossing = NaN;
else
    crossing = time(idx);
end
end

