% Route A Stage 1 normal-operation cEGR target-transition audit.
%
% The one platform_default initial state represents j = 0.1 A/cm^2,
% CEGR-enabled topology, and a mode-1 zero-target near-zero reference. Both
% the cEGR transition and the zero-target reference begin from that exact
% operating point.  The saved Simulink operating point retains its model
% time, so cfg research times are translated to absolute model times here.
% The physical Variant remains mode 1 throughout every same-state comparison.
% Strict mode-0 isolation is verified separately and is not a transition
% baseline because it cannot reuse this operating point.

scriptDir = fileparts(mfilename('fullpath'));
modelDir = fullfile(scriptDir, '..', '..', '01_模型', 'RouteA_GasMixture_Derived');
model = 'PEMFuelCellSystem_GasMixture_cEGR_RouteA_v01';
modelFile = fullfile(modelDir, [model '.slx']);
oldDir = pwd;
addpath(scriptDir);
addpath(modelDir);
cd(modelDir);
routeA_stage1_cleanup = onCleanup(@() routeA_restore_model_and_folder( ...
    model, modelFile, oldDir));

cfg = transitionConfig(modelDir);
baselineAudit = runZeroTargetBaseline(model, modelFile, modelDir, cfg);
resetModelFromDisk(model, modelFile);
refreshModelWorkspace(model);
routeA_apply_constant_current_step(model, ...
    cfg.initialStateMetadata.targetCurrentA, cfg.targetCurrentA);

in = Simulink.SimulationInput(model);
[in, initialStateMetadata] = routeA_attach_platform_default_initial_state( ...
    in, model, modelDir, cfg.initialStateFile);
routeA_mark_observability_signals(model);
in = in.setModelParameter( ...
    'StopTime', sprintf('%.16g', cfg.modelStopTime_s), ...
    'SignalLogging', 'on', ...
    'SignalLoggingName', 'logsout', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SimscapeLogType', 'all');
in = in.setVariable('routeA_air_control_mode_id', 2, 'Workspace', model);
in = in.setVariable('routeA_target_oer', cfg.targetAirEquivalentOer, ...
    'Workspace', model);
in = in.setVariable('routeA_egr_control_mode_id', 1, 'Workspace', model);
in = in.setVariable('routeA_cegr_valve_mode_id', 1, 'Workspace', model);
in = in.setVariable('routeA_target_egr_ratio_comp_in', 0, ...
    'Workspace', model);
in = in.setVariable('routeA_egr_target_input_mode_id', 1, ...
    'Workspace', model);
in = in.setVariable('routeA_target_egr_ratio_comp_in_profile', ...
    cfg.profile, 'Workspace', model);

out = sim(in);
audit = collectAudit(out, model, cfg);
audit.initialState = initialStateMetadata;
audit.zeroTargetBaseline = baselineAudit.systemImpact;
audit.zeroTargetBaselineSteadyState = baselineAudit.steadyState;
audit.systemImpactDeltaMidMinusZeroTarget = impactDelta( ...
    audit.systemImpact.mid, baselineAudit.systemImpact.mid);
audit.systemImpactDeltaPostMinusZeroTarget = impactDelta( ...
    audit.systemImpact.post, baselineAudit.systemImpact.post);
audit.postVsMatchedZeroTarget = returnToInitialStats( ...
    baselineAudit.systemImpact.post, audit.systemImpact.post, cfg);
audit.postVsMatchedZeroTargetPassed = audit.postVsMatchedZeroTarget.passed;
audit.passed = audit.passed && audit.postVsMatchedZeroTargetPassed;
assignin('base', 'routeA_stage1_cegr_transition_audit', audit);
displayAudit(audit);
clear out;
clear routeA_stage1_cleanup;

function cfg = transitionConfig(modelDir)
initialStateFile = fullfile(modelDir, ...
    'RouteA_platform_default_initial_state.mat');
loaded = load(initialStateFile, 'routeA_initial_metadata');
if ~isfield(loaded, 'routeA_initial_metadata')
    error('RouteA:InvalidPlatformDefaultInitialState', ...
        'The platform_default initial-state metadata is unavailable.');
end
metadata = loaded.routeA_initial_metadata;
requiredFields = {'snapshotTimeS', 'targetCurrentA', ...
    'cegrTopologyEnabled', 'cegrValveModeId', 'egrReferenceKind'};
if ~builtin('all', isfield(metadata, requiredFields))
    error('RouteA:InvalidPlatformDefaultInitialStateMetadata', ...
        'The platform_default initial-state metadata is incomplete.');
end
if ~metadata.cegrTopologyEnabled || metadata.cegrValveModeId ~= 1 || ...
        string(metadata.egrReferenceKind) ~= "mode1_zero_target_near_zero"
    error('RouteA:InitialStateModeMismatch', ...
        'The transition audit requires a mode-1 zero-target formal state.');
end

cfg = struct();
cfg.initialStateFile = initialStateFile;
cfg.initialStateMetadata = metadata;
cfg.researchStartTime_s = metadata.snapshotTimeS;
cfg.researchDuration_s = 600;
cfg.modelStopTime_s = cfg.researchStartTime_s + cfg.researchDuration_s;
cfg.targetCurrentA = metadata.targetCurrentA;
cfg.currentTrackingTolerance_A = 5e-3;
cfg.targetAirEquivalentOer = 3;
researchProfile = [ ...
    0, 0; ...
    60, 0; ...
    60.01, 0.10; ...
    240, 0.10; ...
    240.01, 0; ...
    600, 0];
cfg.profile = researchProfile;
cfg.profile(:, 1) = cfg.researchStartTime_s + cfg.profile(:, 1);
cfg.riseCommandTime = cfg.researchStartTime_s + 60.01;
cfg.fallCommandTime = cfg.researchStartTime_s + 240.01;
cfg.transitionLowRatio = 0.01;
cfg.transitionHighRatio = 0.09;
cfg.logicalWindows_s = struct( ...
    'pre', [30, 59], ...
    'mid', [210, 239], ...
    'post', [540, 599]);
cfg.windows = struct( ...
    'pre', cfg.researchStartTime_s + cfg.logicalWindows_s.pre, ...
    'mid', cfg.researchStartTime_s + cfg.logicalWindows_s.mid, ...
    'post', cfg.researchStartTime_s + cfg.logicalWindows_s.post);
cfg.egrTolerance = 0.01;
cfg.tailSpanLimit = 0.01;
cfg.lambdaLowerBound = 1;
cfg.stackCells = 400;
cfg.faradayConstant_C_mol = 96485.33212;
cfg.molarMass_kg_mol = [0.0280134, 0.0319988, 0.00201588, 0.01801528];
cfg.gas = struct( ...
    'n2Index', 1, ...
    'o2Index', 2, ...
    'h2oIndex', 4, ...
    'absoluteResidualTolerance_kg_s', 5e-4, ...
    'relativeResidualTolerance', 0.05);
cfg.steadySpan = struct( ...
    'egrRatio', 0.002, ...
    'egrMdot_kg_s', 5e-4, ...
    'freshAirMdot_kg_s', 5e-4, ...
    'inletTotalMdot_kg_s', 5e-4, ...
    'outletTotalMdot_kg_s', 5e-4, ...
    'stackCurrent_A', 0.5, ...
    'stackVoltage_V', 0.5, ...
    'stackPower_kW', 0.05, ...
    'stackTemperature_C', 0.5, ...
    'compressorMdot_kg_s', 5e-4, ...
    'compressorTemperature_K', 0.5, ...
    'rhCaIn', 0.02, ...
    'rhCaOut', 0.02, ...
    'waterSeparator', 5e-5, ...
    'exhaustMdot_kg_s', 5e-4, ...
    'lambdaCaIn', 0.02, ...
    'inletO2MassFraction', 0.002, ...
    'outletO2MoleFraction', 0.002);
cfg.returnTolerance = struct( ...
    'egrMdot_kg_s', 5e-4, ...
    'freshAirMdot_kg_s', 5e-4, ...
    'inletTotalMdot_kg_s', 5e-4, ...
    'outletTotalMdot_kg_s', 5e-4, ...
    'stackCurrent_A', 0.5, ...
    'stackVoltage_V', 0.5, ...
    'stackPower_kW', 0.05, ...
    'stackTemperature_C', 0.5, ...
    'compressorMdot_kg_s', 5e-4, ...
    'compressorTemperature_K', 0.5, ...
    'rhCaIn', 0.02, ...
    'rhCaOut', 0.02, ...
    'waterSeparator', 5e-5, ...
    'exhaustMdot_kg_s', 5e-4, ...
    'inletO2MassFraction', 0.002, ...
    'inletN2MassFraction', 0.002, ...
    'outletO2MoleFraction', 0.002);
end

function audit = collectAudit(out, model, cfg)
logsout = out.logsout;
ratio = loggedTimeseries(logsout, 'routeA_egr_ratio_comp_in');
area = loggedTimeseries(logsout, 'routeA_egr_valve_area_cmd');
pUp = loggedTimeseries(logsout, 'routeA_p_egr_valve_up');
pDown = loggedTimeseries(logsout, 'routeA_p_egr_valve_down');
compMdot = loggedTimeseries(logsout, 'routeA_mdot_comp_inlet');
compP = loggedTimeseries(logsout, 'routeA_p_comp_inlet');
compT = loggedTimeseries(logsout, 'routeA_T_comp_inlet');
compYi = loggedTimeseries(logsout, 'routeA_yi_comp_inlet');
outletYi = loggedTimeseries(logsout, 'routeA_yi_outlet');
compCmd = loggedTimeseries(logsout, 'routeA_compressor_cmd');
compRpm = loggedTimeseries(logsout, 'routeA_compressor_rpm');
egrMdot = loggedTimeseries(logsout, 'routeA_egr_mdot');
stackCurrent = loggedTimeseries(logsout, 'routeA_stack_current_A');
stackVoltage = loggedTimeseries(logsout, 'routeA_stack_voltage_V');
stackPower = timeseries( ...
    stackCurrent.Data .* stackVoltage.Data * 1e-3, stackCurrent.Time);
stackTemperature = loggedTimeseries(logsout, 'routeA_stack_temperature_C');
rhIn = waterRelativeHumidity(outputTimeseries(out, logsout, ...
    'routeA_RH_ca_in', 'routeA_RH_ca_in_ts'), 'routeA_RH_ca_in');
rhOut = waterRelativeHumidity(outputTimeseries(out, logsout, ...
    'routeA_RH_ca_out', 'routeA_RH_ca_out_ts'), 'routeA_RH_ca_out');
waterSep = outputTimeseries(out, logsout, 'routeA_m_water_sep', ...
    'routeA_m_water_sep_ts');
exhaustMdot = outputTimeseries(out, logsout, 'routeA_exhaust_mdot', ...
    'routeA_exhaust_mdot_ts');

target = profileValue(cfg.profile, ratio.Time);
windows = struct();
windowNames = fieldnames(cfg.windows);
for idx = 1:numel(windowNames)
    name = windowNames{idx};
    windows.(name) = windowStats(ratio, target, cfg.windows.(name));
end

speciesMdot = out.get('routeA_mdot_species_ca_in_ts');
stackCurrentForLambda = out.get('routeA_stack_current_A_ts');
lambda = inletOxygenStoich(speciesMdot, stackCurrentForLambda);
[species, speciesTotal, speciesMassFraction] = inletSpeciesMetrics(speciesMdot);
inletTotalMdot = timeseries(speciesTotal, speciesMdot.Time);
inletO2MassFraction = timeseries(speciesMassFraction(:, 2), speciesMdot.Time);
compYiData = compositionMatrix(compYi, 'routeA_yi_comp_inlet');
compYiMassFraction = moleFractionToMassFraction(compYiData, ...
    cfg.molarMass_kg_mol);
outletYiData = compositionMatrix(outletYi, 'routeA_yi_outlet');
outletYiMassFraction = moleFractionToMassFraction(outletYiData, ...
    cfg.molarMass_kg_mol);
outletO2MoleFraction = timeseries(outletYiData(:, cfg.gas.o2Index), ...
    outletYi.Time);
externalMoleFraction = externalAirMoleFraction(model);
externalMassFraction = moleFractionToMassFraction(externalMoleFraction, ...
    cfg.molarMass_kg_mol);
egrMdotAbs = timeseries(abs(egrMdot.Data), egrMdot.Time);
egrAtCompTime = interp1(egrMdot.Time, egrMdotAbs.Data, ...
    compMdot.Time, 'linear', 'extrap');
freshAirApprox = timeseries(abs(compMdot.Data) - egrAtCompTime, ...
    compMdot.Time);
egrAtOutletTime = interpolateMagnitude(egrMdot, outletYi.Time);
exhaustAtOutletTime = interpolateMagnitude(exhaustMdot, outletYi.Time);
outletTotalMdot = timeseries(egrAtOutletTime + exhaustAtOutletTime, ...
    outletYi.Time);

systemImpact = struct();
windowNames = fieldnames(cfg.windows);
for idx = 1:numel(windowNames)
    name = windowNames{idx};
    window = cfg.windows.(name);
    systemImpact.(name) = systemImpactStats(window, ...
        stackCurrent, stackVoltage, stackPower, stackTemperature, ...
        compMdot, compP, compT, compYi, compCmd, compRpm, ...
        egrMdotAbs, freshAirApprox, ...
        rhIn, rhOut, waterSep, exhaustMdot, inletTotalMdot, ...
        species, speciesMdot.Time, ...
        compYiData, compYiMassFraction, ...
        outletTotalMdot, outletYiData, outletYiMassFraction, outletYi.Time, ...
        externalMoleFraction, externalMassFraction);
end
gasConservation = struct();
for idx = 1:numel(windowNames)
    name = windowNames{idx};
    gasConservation.(name) = gasConservationStats( ...
        systemImpact.(name), cfg);
end
steadyState = struct();
for idx = 1:numel(windowNames)
    name = windowNames{idx};
    window = cfg.windows.(name);
    steadyState.(name) = steadyStateStats(window, cfg, ratio, ...
        stackCurrent, stackVoltage, stackPower, stackTemperature, ...
        compMdot, compT, rhIn, rhOut, waterSep, exhaustMdot, ...
        lambda, inletO2MassFraction, inletTotalMdot, outletTotalMdot, ...
        egrMdotAbs, freshAirApprox, outletO2MoleFraction);
end
steadyPassed = builtin('all', structfun(@(s) s.passed, steadyState));
withinRunPreToPost = returnToInitialStats(systemImpact.pre, ...
    systemImpact.post, cfg);
transitionTiming = transitionTimingStats(ratio, cfg);
inletO2OperationalMask = speciesMdot.Time >= cfg.windows.pre(1) & ...
    speciesMdot.Time <= cfg.windows.post(2);
inletO2NonfiniteOperationalCount = nonfiniteCount( ...
    inletO2MassFraction.Data(inletO2OperationalMask));
inletO2NonfiniteStartupCount = nonfiniteCount(inletO2MassFraction.Data) - ...
    inletO2NonfiniteOperationalCount;

mw = get_param(model, 'ModelWorkspace');
maxArea = mw.getVariable('cegr_valve_max_area');
areaFraction = area.Data / maxArea;
pressureDeltaMPa = (pUp.Data - pDown.Data) * 1e-6;

finiteCounts = struct( ...
    'egrRatio', nonfiniteCount(ratio.Data), ...
    'valveArea', nonfiniteCount(area.Data), ...
    'pressureUpstream', nonfiniteCount(pUp.Data), ...
    'pressureDownstream', nonfiniteCount(pDown.Data), ...
    'compressorMdot', nonfiniteCount(compMdot.Data), ...
    'compressorPressure', nonfiniteCount(compP.Data), ...
    'compressorTemperature', nonfiniteCount(compT.Data), ...
    'compressorInletYi', nonfiniteCount(compYi.Data), ...
    'compressorCommand', nonfiniteCount(compCmd.Data), ...
    'compressorRpm', nonfiniteCount(compRpm.Data), ...
    'egrMdot', nonfiniteCount(egrMdot.Data), ...
    'outletYi', nonfiniteCount(outletYiData), ...
    'outletTotalMdot', nonfiniteCount(outletTotalMdot.Data), ...
    'stackCurrent', nonfiniteCount(stackCurrent.Data), ...
    'stackVoltage', nonfiniteCount(stackVoltage.Data), ...
    'stackPower', nonfiniteCount(stackPower.Data), ...
    'stackTemperature', nonfiniteCount(stackTemperature.Data), ...
    'rhCaIn', nonfiniteCount(rhIn.Data), ...
    'rhCaOut', nonfiniteCount(rhOut.Data), ...
    'waterSeparator', nonfiniteCount(waterSep.Data), ...
    'exhaustMdot', nonfiniteCount(exhaustMdot.Data), ...
    'inletSpeciesMdot', nonfiniteCount(species), ...
    'inletTotalMdot', nonfiniteCount(inletTotalMdot.Data), ...
    'inletO2MassFraction', nonfiniteCount(inletO2MassFraction.Data), ...
    'lambdaCaIn', nonfiniteCount(lambda.Data));
finiteCountsPhysical = rmfield(finiteCounts, ...
    {'lambdaCaIn', 'inletO2MassFraction'});
finiteOk = builtin('all', struct2array(finiteCountsPhysical) == 0) && ...
    inletO2NonfiniteOperationalCount == 0;
trackingPassed = windows.pre.meanAbsError <= cfg.egrTolerance && ...
    windows.mid.meanAbsError <= cfg.egrTolerance && ...
    windows.post.meanAbsError <= cfg.egrTolerance && ...
    windows.pre.tailSpan <= cfg.tailSpanLimit && ...
    windows.mid.tailSpan <= cfg.tailSpanLimit && ...
    windows.post.tailSpan <= cfg.tailSpanLimit;
pressurePassed = mean(pressureDeltaMPa(windowMask(pUp, cfg.windows.mid))) > 0;
areaPassed = min(areaFraction) >= 0 && max(areaFraction) < 1 - 1e-6;
lambdaOperationalMask = lambda.Time >= cfg.windows.pre(1) & ...
    lambda.Time <= cfg.windows.post(2);
lambdaNonfiniteOperationalCount = nonfiniteCount( ...
    lambda.Data(lambdaOperationalMask));
lambdaNonfiniteStartupCount = finiteCounts.lambdaCaIn - ...
    lambdaNonfiniteOperationalCount;
lambdaOperationalMin = min(lambda.Data(lambdaOperationalMask));
lambdaPassed = lambdaOperationalMin > cfg.lambdaLowerBound;
currentOperationalMask = stackCurrent.Time >= cfg.researchStartTime_s & ...
    stackCurrent.Time <= cfg.modelStopTime_s;
currentTrackingErrorA = max(abs( ...
    stackCurrent.Data(currentOperationalMask) - cfg.targetCurrentA));
currentPassed = currentTrackingErrorA <= cfg.currentTrackingTolerance_A;

audit = struct();
audit.timestamp = string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));
audit.model = string(model);
audit.researchStartModelTime_s = cfg.researchStartTime_s;
audit.researchDuration_s = cfg.researchDuration_s;
audit.modelStopTime_s = cfg.modelStopTime_s;
audit.profile = cfg.profile;
audit.logicalWindows_s = cfg.logicalWindows_s;
audit.windows = windows;
audit.systemImpact = systemImpact;
audit.gasConservation = gasConservation;
audit.gasObservability = gasObservability();
audit.gasConservationPassed = builtin('all', ...
    structfun(@(s) s.passed, gasConservation));
audit.steadyState = steadyState;
audit.steadyPassed = steadyPassed;
audit.withinRunPreToPost = withinRunPreToPost;
audit.withinRunPreToPostPassed = withinRunPreToPost.passed;
audit.systemImpactDeltaMidMinusPre = impactDelta( ...
    systemImpact.mid, systemImpact.pre);
audit.transitionTiming = transitionTiming;
audit.inletSpeciesComponentIndexO2 = 2;
audit.targetCurrentA = cfg.targetCurrentA;
audit.currentTrackingMaxErrorA = currentTrackingErrorA;
audit.actualPowerKW = stackPower.Data(end);
audit.stackPowerTailSpanKW = tailSpan(stackPower.Data);
audit.lambdaCaInMin = min(lambda.Data);
audit.lambdaCaInOperationalMin = lambdaOperationalMin;
audit.pressureDeltaMidMPa = mean(pressureDeltaMPa(windowMask(pUp, cfg.windows.mid)));
audit.valveAreaFractionMin = min(areaFraction);
audit.valveAreaFractionMax = max(areaFraction);
audit.compressorMdotFinalKgS = compMdot.Data(end);
audit.compressorPressureFinalPa = compP.Data(end);
audit.compressorTemperatureFinal = compT.Data(end);
audit.rhCaInFinal = rhIn.Data(end);
audit.rhCaOutFinal = rhOut.Data(end);
audit.waterSepFinal = waterSep.Data(end);
audit.exhaustMdotFinalKgS = exhaustMdot.Data(end);
audit.nonfiniteCounts = finiteCounts;
audit.lambdaNonfiniteOperationalCount = lambdaNonfiniteOperationalCount;
audit.lambdaNonfiniteStartupCount = lambdaNonfiniteStartupCount;
audit.inletO2NonfiniteOperationalCount = inletO2NonfiniteOperationalCount;
audit.inletO2NonfiniteStartupCount = inletO2NonfiniteStartupCount;
audit.finiteOk = finiteOk && lambdaNonfiniteOperationalCount == 0;
audit.trackingPassed = trackingPassed;
audit.pressurePassed = pressurePassed;
audit.areaPassed = areaPassed;
audit.lambdaPassed = lambdaPassed;
audit.currentPassed = currentPassed;
audit.passed = finiteOk && trackingPassed && pressurePassed && ...
    areaPassed && lambdaPassed && currentPassed && steadyPassed && ...
    audit.gasConservationPassed;
end

function stats = windowStats(signal, target, window)
mask = signal.Time >= window(1) & signal.Time <= window(2);
actual = signal.Data(mask);
expected = target(mask);
stats = struct();
stats.start_s = window(1);
stats.end_s = window(2);
stats.targetMean = mean(expected);
stats.actualMean = mean(actual);
stats.meanAbsError = mean(abs(actual - expected));
stats.actualMin = min(actual);
stats.actualMax = max(actual);
stats.tailSpan = max(actual) - min(actual);
end

function stats = systemImpactStats(window, stackCurrent, stackVoltage, ...
    stackPower, stackTemperature, compMdot, compP, compT, compYi, ...
    compCmd, compRpm, egrMdot, ...
    freshAir, rhIn, rhOut, waterSep, exhaustMdot, inletTotalMdot, ...
    speciesMdot, speciesTime, ...
    compYiData, compYiMassFraction, ...
    outletTotalMdot, outletYiData, outletYiMassFraction, outletYiTime, ...
    externalMoleFraction, externalMassFraction)
stats = struct();
stats.window_s = window;
stats.stackCurrent_A = windowMean(stackCurrent, window);
stats.stackVoltage_V = windowMean(stackVoltage, window);
stats.stackPower_kW = windowMean(stackPower, window);
stats.stackTemperature_C = windowMean(stackTemperature, window);
stats.compressorMdot_kg_s = windowMean(compMdot, window);
stats.compressorPressure_Pa = windowMean(compP, window);
stats.compressorTemperature_K = windowMean(compT, window);
stats.compressorCommand = windowMean(compCmd, window);
stats.compressorRpm = windowMean(compRpm, window);
stats.egrMdot_kg_s = windowMean(egrMdot, window);
stats.freshAirApprox_kg_s = windowMean(freshAir, window);
stats.rhCaIn = windowMean(rhIn, window);
stats.rhCaOut = windowMean(rhOut, window);
stats.waterSeparator = windowMean(waterSep, window);
stats.exhaustMdot_kg_s = windowMean(exhaustMdot, window);
stats.cathodeInletTotalMdot_kg_s = windowMean(inletTotalMdot, window);
mask = speciesTime >= window(1) & speciesTime <= window(2);
stats.cathodeInletSpeciesMdot_kg_s = mean(speciesMdot(mask, :), 1);
stats.cathodeInletSpeciesMassFraction = normalizeComposition( ...
    stats.cathodeInletSpeciesMdot_kg_s);
compYiMask = compYi.Time >= window(1) & compYi.Time <= window(2);
stats.compressorInletYi = mean(compYiData(compYiMask, :), 1);
stats.compressorInletMassFraction = mean(compYiMassFraction(compYiMask, :), 1);
stats.compressorInletSpeciesMdot_kg_s = ...
    abs(stats.compressorMdot_kg_s) * stats.compressorInletMassFraction;
outletMask = outletYiTime >= window(1) & outletYiTime <= window(2);
stats.cathodeOutletTotalMdot_kg_s = windowMean(outletTotalMdot, window);
stats.cathodeOutletYi = mean(outletYiData(outletMask, :), 1);
stats.cathodeOutletSpeciesMassFraction = normalizeComposition( ...
    mean(outletYiMassFraction(outletMask, :), 1));
stats.cathodeOutletSpeciesMdot_kg_s = ...
    stats.cathodeOutletTotalMdot_kg_s * ...
    stats.cathodeOutletSpeciesMassFraction;
stats.cathodeRecycleMdot_kg_s = stats.egrMdot_kg_s;
stats.cathodeRecycleYi = stats.cathodeOutletYi;
stats.cathodeRecycleSpeciesMassFraction = ...
    stats.cathodeOutletSpeciesMassFraction;
stats.freshAirMdot_kg_s = stats.freshAirApprox_kg_s;
stats.externalMoleFraction = externalMoleFraction;
stats.externalMassFraction = externalMassFraction;
stats.freshAirSpeciesMdot_kg_s = ...
    stats.freshAirMdot_kg_s * externalMassFraction;
end

function stats = gasConservationStats(impact, cfg)
n2 = cfg.gas.n2Index;
o2 = cfg.gas.o2Index;
h2o = cfg.gas.h2oIndex;
inlet = impact.cathodeInletSpeciesMdot_kg_s;
outlet = impact.cathodeOutletSpeciesMdot_kg_s;
fresh = impact.freshAirSpeciesMdot_kg_s;
recycle = impact.cathodeRecycleMdot_kg_s * ...
    impact.cathodeOutletSpeciesMassFraction;
compressor = impact.compressorInletSpeciesMdot_kg_s;
mixExpected = fresh + recycle;
stackCurrent = abs(impact.stackCurrent_A);
o2Faraday = cfg.stackCells * stackCurrent / ...
    (4 * cfg.faradayConstant_C_mol) * cfg.molarMass_kg_mol(o2);
stats = struct();
stats.window_s = impact.window_s;
stats.inletSpeciesMdot_kg_s = inlet;
stats.outletSpeciesMdot_kg_s = outlet;
stats.freshAirSpeciesMdot_kg_s = fresh;
stats.recycleSpeciesMdot_kg_s = recycle;
stats.compressorInletSpeciesMdot_kg_s = compressor;
stats.mixExpectedSpeciesMdot_kg_s = mixExpected;
stats.n2StackResidual_kg_s = inlet(n2) - outlet(n2);
stats.o2NetConsumption_kg_s = inlet(o2) - outlet(o2);
stats.o2FaradayConsumption_kg_s = o2Faraday;
stats.o2FaradayResidual_kg_s = ...
    stats.o2NetConsumption_kg_s - o2Faraday;
stats.h2oNetResidual_kg_s = inlet(h2o) - outlet(h2o);
stats.mixResidualSpeciesMdot_kg_s = compressor - mixExpected;
stats.n2MixResidual_kg_s = stats.mixResidualSpeciesMdot_kg_s(n2);
stats.o2MixResidual_kg_s = stats.mixResidualSpeciesMdot_kg_s(o2);
