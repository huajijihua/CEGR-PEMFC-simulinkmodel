stats.outletFlowClosure_kg_s = impact.cathodeOutletTotalMdot_kg_s - ...
    impact.cathodeRecycleMdot_kg_s - impact.exhaustMdot_kg_s;
stats.n2StackPassed = residualPassed(stats.n2StackResidual_kg_s, ...
    max(abs(inlet(n2)), abs(outlet(n2))), cfg.gas);
stats.o2FaradayPassed = residualPassed(stats.o2FaradayResidual_kg_s, ...
    max(abs(stats.o2NetConsumption_kg_s), abs(o2Faraday)), cfg.gas);
