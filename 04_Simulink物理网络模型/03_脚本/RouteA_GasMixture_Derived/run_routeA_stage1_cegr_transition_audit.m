function lambda = inletOxygenStoich(speciesMdot, stackCurrent)
species = squeeze(speciesMdot.Data).';
if size(species, 1) ~= numel(speciesMdot.Time) || size(species, 2) < 2
    error('RouteA:Stage1SpeciesFlowShape', ...
        'Unexpected cathode inlet species-flow data shape.');
end
current = stackCurrent.Data(:);
currentAtSpeciesTime = interp1(stackCurrent.Time, current, ...
    speciesMdot.Time, 'linear', 'extrap');
o2SupplyMolS = abs(species(:, 2)) / 0.0319988;
o2ConsumptionMolS = 400 * abs(currentAtSpeciesTime) / (4 * 96485.33212);
lambda = timeseries(o2SupplyMolS ./ o2ConsumptionMolS, speciesMdot.Time);
end

