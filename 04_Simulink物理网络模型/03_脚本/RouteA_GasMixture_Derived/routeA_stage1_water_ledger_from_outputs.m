function cfg = normalizeLoadTrackingConfig(cfg)
if ~isfield(cfg, 'loadTrackingMode') || isempty(cfg.loadTrackingMode)
    cfg.loadTrackingMode = "constant_current";
end
mode = string(cfg.loadTrackingMode);
if ~isscalar(mode) || ~any(mode == ["constant_current", "constant_power", ...
        "constant_voltage"])
    error('RouteA:WaterLedgerLoadTrackingMode', ...
        ['loadTrackingMode must be constant_current, constant_power, ', ...
        'or constant_voltage.']);
end
cfg.loadTrackingMode = mode;

if mode == "constant_current"
    required = {'targetCurrentA', 'currentTrackingTolerance_A'};
    if ~builtin('all', isfield(cfg, required))
        error('RouteA:WaterLedgerCurrentTrackingConfig', ...
            'The constant-current tracking configuration is incomplete.');
    end
    validateattributes(cfg.targetCurrentA, {'numeric'}, ...
        {'scalar', 'finite'});
    validateattributes(cfg.currentTrackingTolerance_A, {'numeric'}, ...
        {'scalar', 'nonnegative', 'finite'});
    if ~isfield(cfg, 'currentTrackingWindow_s')
        cfg.currentTrackingWindow_s = [cfg.researchStartTime_s, ...
            cfg.modelStopTime_s];
    end
    validateTrackingWindow(cfg.currentTrackingWindow_s, ...
        cfg.researchStartTime_s, cfg.modelStopTime_s, 'currentTrackingWindow_s');
elseif mode == "constant_power"
    required = {'targetPower_kW', 'powerTrackingRelativeTolerance', ...
        'powerTrackingWindow_s'};
    if ~builtin('all', isfield(cfg, required))
        error('RouteA:WaterLedgerPowerTrackingConfig', ...
            'The constant-power tracking configuration is incomplete.');
    end
    validateattributes(cfg.targetPower_kW, {'numeric'}, ...
        {'scalar', 'positive', 'finite'});
    validateattributes(cfg.powerTrackingRelativeTolerance, {'numeric'}, ...
        {'scalar', 'nonnegative', 'finite'});
    validateTrackingWindow(cfg.powerTrackingWindow_s, ...
        cfg.researchStartTime_s, cfg.modelStopTime_s, 'powerTrackingWindow_s');
else
    required = {'targetVoltage_V', 'voltageTrackingRelativeTolerance', ...
        'voltageTrackingWindow_s'};
    if ~builtin('all', isfield(cfg, required))
        error('RouteA:WaterLedgerVoltageTrackingConfig', ...
            'The constant-voltage tracking configuration is incomplete.');
    end
    validateattributes(cfg.targetVoltage_V, {'numeric'}, ...
        {'scalar', 'positive', 'finite'});
    validateattributes(cfg.voltageTrackingRelativeTolerance, {'numeric'}, ...
        {'scalar', 'nonnegative', 'finite'});
    validateTrackingWindow(cfg.voltageTrackingWindow_s, ...
        cfg.researchStartTime_s, cfg.modelStopTime_s, 'voltageTrackingWindow_s');
end
end

function validateTrackingWindow(window, lowerBound, upperBound, name)
validateattributes(window, {'numeric'}, {'vector', 'numel', 2, 'finite'});
window = window(:).';
if window(1) < lowerBound || window(2) > upperBound || ...
        window(2) <= window(1)
    error('RouteA:WaterLedgerTrackingWindow', ...
        '%s must be increasing and within the research window.', name);
end
end

function tracking = assessLoadTracking(stackCurrent, stackPower, stackVoltage, cfg)
tracking = struct( ...
    'mode', cfg.loadTrackingMode, ...
    'window_s', NaN(1, 2), ...
    'currentWindow_s', NaN(1, 2), ...
    'powerWindow_s', NaN(1, 2), ...
    'voltageWindow_s', NaN(1, 2), ...
    'currentMaxError_A', NaN, ...
    'currentPassed', NaN, ...
    'powerMaxRelativeError', NaN, ...
    'powerPassed', NaN, ...
    'voltageMaxRelativeError', NaN, ...
    'voltageTailMeanRelativeError', NaN, ...
    'voltagePassed', NaN, ...
    'passed', false);
if cfg.loadTrackingMode == "constant_current"
    currentData = normalizeScalarData(stackCurrent.Time, stackCurrent.Data, ...
        'stack current');
    values = windowData(stackCurrent.Time, currentData, ...
        cfg.currentTrackingWindow_s);
    tracking.window_s = cfg.currentTrackingWindow_s;
    tracking.currentWindow_s = cfg.currentTrackingWindow_s;
    tracking.currentMaxError_A = max(abs(values - cfg.targetCurrentA));
    tracking.currentPassed = tracking.currentMaxError_A <= ...
        cfg.currentTrackingTolerance_A;
    tracking.passed = tracking.currentPassed;
elseif cfg.loadTrackingMode == "constant_power"
    powerData = normalizeScalarData(stackPower.Time, stackPower.Data, ...
        'stack power');
    values = windowData(stackPower.Time, powerData, ...
        cfg.powerTrackingWindow_s);
    tracking.window_s = cfg.powerTrackingWindow_s;
    tracking.powerWindow_s = cfg.powerTrackingWindow_s;
    tracking.powerMaxRelativeError = max(abs(values - cfg.targetPower_kW)) / ...
        max(abs(cfg.targetPower_kW), 1e-6);
    tracking.powerPassed = tracking.powerMaxRelativeError <= ...
        cfg.powerTrackingRelativeTolerance;
    tracking.passed = tracking.powerPassed;
else
    voltageData = normalizeScalarData(stackVoltage.Time, stackVoltage.Data, ...
        'stack voltage');
    values = windowData(stackVoltage.Time, voltageData, ...
        cfg.voltageTrackingWindow_s);
    tracking.window_s = cfg.voltageTrackingWindow_s;
    tracking.voltageWindow_s = cfg.voltageTrackingWindow_s;
    tracking.voltageMaxRelativeError = ...
        max(abs(values - cfg.targetVoltage_V)) / ...
        max(abs(cfg.targetVoltage_V), 1e-6);
    tracking.voltageTailMeanRelativeError = ...
        abs(mean(values) - cfg.targetVoltage_V) / ...
        max(abs(cfg.targetVoltage_V), 1e-6);
    tracking.voltagePassed = tracking.voltageTailMeanRelativeError <= ...
        cfg.voltageTrackingRelativeTolerance;
    tracking.passed = tracking.voltagePassed;
end
end

function audit = summarizeWaterAudit(cases, cfg)
audit = struct();
audit.timestamp = string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));
audit.model = string(cfg.initialStateMetadata.model);
audit.initialState = cfg.initialStateMetadata;
audit.targetRatios = cfg.targetRatios;
if isfield(cases, 'loadId')
    audit.loadIds = unique(string({cases.loadId}), 'stable');
else
    audit.loadIds = string.empty(1, 0);
end
audit.researchDuration_s = cfg.researchDuration_s;
audit.tailLogicalWindow_s = cfg.tailLogicalWindow_s;
audit.scope = 'cathode-cEGR water side only';
audit.cases = cases;
audit.observability = observabilityMap();
audit.localGasPhaseClosurePassed = ...
    builtin('all', [cases.localGasPhaseBalancePassed]);
audit.systemGasPhaseClosurePassed = ...
    builtin('all', [cases.systemGasPhaseBalancePassed]);
audit.gasVaporAndPhaseFluxEvidencePassed = ...
    builtin('all', [cases.evidencePassed]);
audit.liquidWaterInventoryClosed = false;
audit.liquidWaterTransportClosed = false;
audit.liquidDrainClosed = false;
audit.separatorEfficiencyClosed = false;
audit.fullWaterBalanceClosed = false;
audit.liquidGapReason = [ ...
    "No explicit liquid-water port, liquid transport branch, drain flow, ", ...
    "or separator efficiency model is currently exposed by the cathode-cEGR ", ...
    "physical network. Enabled Constant Volume Chamber (FC) blocks remove ", ...
    "condensed species from the gas chamber immediately; m_I_i is the ", ...
    "remaining gas-species inventory, not a liquid-water inventory."];
audit.auditPassed = audit.gasVaporAndPhaseFluxEvidencePassed;
end

function observability = observabilityMap()
observability = struct( ...
    'externalAirWater', ...
        'direct: fresh-air branch at CompressorInletMixer port-A species flow', ...
    'cathodeHumidifierWaterInput', ...
