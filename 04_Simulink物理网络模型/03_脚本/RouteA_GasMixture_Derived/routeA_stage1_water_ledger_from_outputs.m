function data = normalizeSeriesData(data, time, label)
data = squeeze(data);
if isvector(data)
    data = data(:);
end
if size(data, 1) ~= numel(time)
    data = data.';
end
if size(data, 1) ~= numel(time)
    error('RouteA:WaterAuditSeriesShape', ...
        'Unexpected Simscape data shape for %s.', label);
end
end

