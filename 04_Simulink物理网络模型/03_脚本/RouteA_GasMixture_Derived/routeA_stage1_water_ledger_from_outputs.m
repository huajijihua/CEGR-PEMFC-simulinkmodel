function rate = inventoryRate(time, data, window)
mask = time >= window(1) & time < window(2);
time = time(mask);
data = data(mask, :);
if numel(time) < 2 || time(end) <= time(1)
    rate = NaN(1, size(data, 2));
    return;
end
rate = (data(end, :) - data(1, :)) / (time(end) - time(1));
end

function balance = localGasPhaseBalance(ports, condensate, inventory, ...
    speciesIndex, window, cfg, label)
time = inventory.time;
mask = time >= window(1) & time <= window(2);
time = time(mask);
inventoryData = inventory.data(mask, speciesIndex);
balance = struct();
balance.label = label;
balance.window_s = window;
balance.sampleCount = numel(time);
if numel(time) < 2 || time(end) <= time(1)
    balance.integratedPortAndCondensation_kg = NaN;
    balance.deltaGasInventory_kg = NaN;
    balance.residual_kg = NaN;
    balance.tolerance_kg = NaN;
    balance.passed = false;
    return;
end

portA = resampleSpecies(ports.A, time, speciesIndex, label);
portB = resampleSpecies(ports.B, time, speciesIndex, label);
portC = resampleSpecies(ports.C, time, speciesIndex, label);
condRate = resampleSpecies(condensate, time, speciesIndex, label);
netGasRate = portA + portB + portC - condRate;
integratedNet = trapz(time, netGasRate);
deltaInventory = inventoryData(end) - inventoryData(1);
residual = integratedNet - deltaInventory;
throughput = trapz(time, abs(portA) + abs(portB) + abs(portC) + abs(condRate));
tolerance = cfg.localGasBalanceAbsTolerance_kg + ...
    cfg.localGasBalanceRelativeTolerance * max(throughput, 1e-12);
balance.integratedPortAndCondensation_kg = integratedNet;
balance.deltaGasInventory_kg = deltaInventory;
balance.residual_kg = residual;
balance.tolerance_kg = tolerance;
balance.passed = isfinite(residual) && abs(residual) <= tolerance;
end

function balance = cathodeSystemGasPhaseBalance(freshAir, humidifier, ...
    meaCathode, exhaustPortB, condensateSignals, inventorySignals, speciesIndex, ...
    window, cfg)
time = inventorySignals(1).time;
mask = time >= window(1) & time <= window(2);
time = time(mask);
balance = struct();
balance.window_s = window;
balance.sampleCount = numel(time);
if numel(time) < 2 || time(end) <= time(1)
    balance.integratedFreshAir_kg = NaN;
    balance.integratedHumidifier_kg = NaN;
    balance.integratedMeaCathode_kg = NaN;
    balance.integratedExhaust_kg = NaN;
    balance.integratedCondensation_kg = NaN;
    balance.deltaGasInventory_kg = NaN;
    balance.residual_kg = NaN;
    balance.tolerance_kg = NaN;
    balance.passed = false;
    return;
end

freshRate = resampleSpecies(freshAir, time, speciesIndex, 'fresh-air water');
humidifierRate = resampleSpecies(humidifier, time, speciesIndex, ...
    'humidifier water source');
meaRate = resampleSpecies(meaCathode, time, speciesIndex, ...
    'MEA cathode water source');
exhaustRate = -resampleSpecies(exhaustPortB, time, speciesIndex, ...
    'final exhaust water flow');
condensationRate = zeros(size(time));
for idx = 1:numel(condensateSignals)
    condensationRate = condensationRate + resampleSpecies( ...
        condensateSignals(idx), time, speciesIndex, 'condensation flow');
end
gasInventory = zeros(size(time));
for idx = 1:numel(inventorySignals)
    gasInventory = gasInventory + resampleSpecies( ...
        inventorySignals(idx), time, speciesIndex, 'gas water inventory');
end

integratedFreshAir = trapz(time, freshRate);
integratedHumidifier = trapz(time, humidifierRate);
integratedMeaCathode = trapz(time, meaRate);
integratedExhaust = trapz(time, exhaustRate);
integratedCondensation = trapz(time, condensationRate);
deltaGasInventory = gasInventory(end) - gasInventory(1);
integratedNet = integratedFreshAir + integratedHumidifier + ...
    integratedMeaCathode - integratedExhaust - integratedCondensation;
residual = integratedNet - deltaGasInventory;
throughput = trapz(time, abs(freshRate) + abs(humidifierRate) + ...
    abs(meaRate) + abs(exhaustRate) + abs(condensationRate));
tolerance = cfg.systemGasBalanceAbsTolerance_kg + ...
    cfg.systemGasBalanceRelativeTolerance * max(throughput, 1e-12);
balance.integratedFreshAir_kg = integratedFreshAir;
balance.integratedHumidifier_kg = integratedHumidifier;
balance.integratedMeaCathode_kg = integratedMeaCathode;
balance.integratedExhaust_kg = integratedExhaust;
balance.integratedCondensation_kg = integratedCondensation;
balance.deltaGasInventory_kg = deltaGasInventory;
balance.integratedNet_kg = integratedNet;
balance.residual_kg = residual;
balance.tolerance_kg = tolerance;
balance.passed = isfinite(residual) && abs(residual) <= tolerance;
end

function stats = saturationRatioStats(node, cfg, label)
pressure = logSeries(node, 'p_I', 'Pa', [label ' p_I']);
temperature = logSeries(node, 'T_I', 'K', [label ' T_I']);
moleFraction = logSeries(node, 'y_I_i', '1', [label ' y_I_i']);
time = pressure.time;
p = resampleSpecies(pressure, time, 1, label);
T = resampleSpecies(temperature, time, 1, label);
yH2O = resampleSpecies(moleFraction, time, cfg.species.h2o, label);
temperatureC = T - 273.15;
pSatPa = 611.21 .* exp((18.678 - temperatureC ./ 234.5) .* ...
    (temperatureC ./ (257.14 + temperatureC)));
ratio = yH2O .* p ./ pSatPa;
fullMask = time >= cfg.researchStartTime_s & time <= cfg.modelStopTime_s;
tailMask = time >= cfg.tailWindow_s(1) & time < cfg.tailWindow_s(2);
if ~any(fullMask) || ~any(tailMask) || any(~isfinite(ratio))
    error('RouteA:WaterAuditSaturation', ...
        'Could not evaluate water saturation ratio for %s.', label);
end
stats = struct();
stats.fullMaximum = max(ratio(fullMask));
stats.tailMaximum = max(ratio(tailMask));
stats.tailMean = mean(ratio(tailMask));
stats.tailMinimum = min(ratio(tailMask));
end

function values = resampleSpecies(signal, targetTime, speciesIndex, label)
if size(signal.data, 2) < speciesIndex
    error('RouteA:WaterAuditMissingSpecies', ...
        'Water species is unavailable in %s.', label);
end
sourceTime = signal.time;
sourceData = signal.data(:, speciesIndex);
if numel(sourceTime) == numel(targetTime) && isequal(sourceTime, targetTime)
    values = sourceData;
    return;
end
values = interp1(sourceTime, sourceData, targetTime, 'linear');
if any(~isfinite(values))
    error('RouteA:WaterAuditResample', ...
        'Could not align the water flow time base for %s.', label);
end
end

function values = windowData(time, data, window)
mask = time >= window(1) & time < window(2);
values = data(mask, :);
if isempty(values)
    error('RouteA:WaterAuditEmptyWindow', ...
        'No samples were found in the requested statistics window.');
end
end

