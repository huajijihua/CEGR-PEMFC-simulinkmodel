    params.controls.current_default_ref_A.value, 0, 392, ...
    "platform_default", "drive_cycle_current", "", "", "runtime", "no", ...
    "validated", "low", "Current-mode FromWorkspace data column.", "active");
add("electrical.power.profile", "Power command", "electrical", "kW", ...
    params.controls.power_default_ref_kW.value, 0, 150, ...
    "platform_default", "drive_cycle_power", "", "", "runtime", "no", ...
    "validated", "low", "Power-mode FromWorkspace data column.", "active");
add("electrical.voltage.profile", "Voltage command", "electrical", "V", ...
    params.controls.voltage_default_ref_V.value, 0, 500, ...
    "platform_default", "drive_cycle_voltage", "", "", "runtime", "no", ...
    "validated", "low", "Voltage-mode reference data column.", "active");
add("electrical.voltageController.Kp_A_V", "Voltage PI Kp", "electrical", "A/V", ...
    params.controls.voltage_pi_Kp.value, 0, Inf, "platform_default", ...
    "routeA_voltage_pi_Kp", "", "", "controller", "compile", ...
    "validated", "medium", "Voltage controller proportional gain.", "active");
add("electrical.voltageController.Ki_A_V_s", "Voltage PI Ki", "electrical", "A/V/s", ...
    params.controls.voltage_pi_Ki.value, 0, Inf, "platform_default", ...
    "routeA_voltage_pi_Ki", "", "", "controller", "compile", ...
    "validated", "medium", "Voltage controller integral gain.", "active");
add("electrical.voltageController.currentMin_A", "Voltage current lower limit", ...
    "electrical", "A", params.controls.voltage_current_min_A.value, 0, 392, ...
    "platform_default", "routeA_voltage_current_min_A", "", "", "controller", ...
    "compile", "validated", "medium", "Voltage controller lower saturation.", "active");
add("electrical.voltageController.currentMax_A", "Voltage current upper limit", ...
    "electrical", "A", params.controls.voltage_current_max_A.value, 0, 392, ...
    "platform_default", "routeA_voltage_current_max_A", "", "", "controller", ...
    "compile", "validated", "medium", "Voltage controller upper saturation.", "active");

add("cathode.airControlMode", "Air control mode", "cathode", "-", ...
    params.controls.air_control_mode.value, 1, 3, "platform_default", ...
    "routeA_air_control_mode_id", "", "", "controller", "compile", ...
    "validated", "medium", "1=mass flow, 2=OER, 3=direct command.", "active");
add("cathode.targetOer", "Target OER", "cathode", "-", ...
    params.controls.target_oer.value, 1.5, 5, "platform_default", ...
    "routeA_command_profile", "", "air_target_oer", "runtime", "no", ...
    "validated", "medium", "Fresh-air oxygen excess ratio target.", "active");
add("cathode.targetMdot_kg_s", "Target cathode mass flow", "cathode", "kg/s", ...
    params.controls.target_mdot_kg_s.value, 0, Inf, "platform_default", ...
    "routeA_command_profile", "", "air_target_mdot_kg_s", "runtime", "no", ...
    "validated", "medium", "Fresh-air mass-flow target.", "active");
add("cathode.outletPressure_MPa_abs", "Cathode outlet pressure", "cathode", ...
    "MPa(abs)", params.controls.backpressure_MPa_abs.value, 0.1, 0.3, ...
    "platform_default", "routeA_command_profile", "", ...
    "cathode_outlet_pressure_MPa_abs", "runtime", "no", "validated", "medium", ...
    "Cathode exhaust backpressure setpoint.", "active");
add("cathode.humidifierRH", "Cathode humidifier RH", "cathode", "-", ...
    params.cathode.humidifier.default_rh.value, 0, 1, "platform_default", ...
    "routeA_command_profile", "", "cathode_humidifier_rh", "runtime", "no", ...
    "validated", "medium", "Cathode humidifier relative humidity command.", "active");
add("cathode.o2MoleFraction", "Cathode inlet O2 fraction", "cathode", "-", ...
    params.environment.o2_mole_fraction.value, 0.15, 0.21, "platform_default", ...
    "env_yO2", "", "", "compile", "compile", "validated", "medium", ...
    "Air Intake reservoir compile-time O2 composition.", "active");
