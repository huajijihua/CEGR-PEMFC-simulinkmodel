function registry = routeA_parameter_registry(paths)
% Return the Route A parameter registry for platform and study inputs.
%
% Active entries describe parameters that the current SimulationInput chain
% can set. Platform leaves are also inventoried, but remain closed to the UI
% until their range, model mapping, compile behavior, and response are known.

