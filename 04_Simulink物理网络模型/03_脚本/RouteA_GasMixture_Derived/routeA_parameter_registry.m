    params.numerics.maxStep_s.value, 0, Inf, "platform_default", "", "", "", ...
    "study", "no", "validated", "medium", "Maximum solver step size.", "active");

% Inventory every platform-default leaf that is not yet an active input.
entries = appendPlatformLeaves(entries, params, '');

registry = struct();
registry.schemaVersion = "RouteA_Parameter_Registry_v01";
registry.model = string(paths.modelName);
registry.sourceFunction = "routeA_platform_default_parameters";
registry.entries = entries;
registry.count = numel(entries);
registry.activeCount = sum(arrayfun(@(x) x.status == "active", entries));
registry.inventoryCount = sum(arrayfun(@(x) x.status == "inventory", entries));
registry.generatedAt = string(datetime('now', 'Format', 'yyyy-MM-dd HH:mm:ss'));

    function add(canonicalName, displayName, domain, unit, defaultValue, ...
            minimum, maximum, source, modelWorkspaceVariable, blockParameter, ...
            profileField, tunableClass, requiresCompile, validationLevel, ...
            riskLevel, description, status)
        entry = entryTemplate();
        entry.canonicalName = string(canonicalName);
        entry.displayName = string(displayName);
        entry.domain = string(domain);
        entry.unit = string(unit);
        entry.defaultValue = defaultValue;
        entry.minimum = minimum;
        entry.maximum = maximum;
        entry.source = string(source);
        entry.modelWorkspaceVariable = string(modelWorkspaceVariable);
        entry.blockParameter = string(blockParameter);
        entry.profileField = string(profileField);
        entry.tunableClass = string(tunableClass);
        entry.requiresCompile = string(requiresCompile);
        entry.validationLevel = string(validationLevel);
        entry.riskLevel = string(riskLevel);
        entry.description = string(description);
        entry.status = string(status);
        entries(end + 1) = entry;
    end
end

function entries = appendPlatformLeaves(entries, value, prefix)
if isstruct(value) && isscalar(value) && ...
        isfield(value, 'value') && isfield(value, 'unit') && ...
        isfield(value, 'source') && isfield(value, 'description')
    entry = entryTemplate();
    entry.canonicalName = "platform." + string(prefix);
    entry.displayName = entry.canonicalName;
    entry.domain = firstToken(prefix);
    entry.unit = string(value.unit);
    entry.defaultValue = value.value;
    entry.minimum = [];
    entry.maximum = [];
    entry.source = "routeA_platform_default_parameters." + string(prefix);
    entry.modelWorkspaceVariable = "";
    entry.blockParameter = "";
    entry.profileField = "";
    entry.tunableClass = "inventory";
    entry.requiresCompile = "unknown";
    entry.validationLevel = "inventory";
    entry.riskLevel = "unknown";
    entry.description = string(value.description);
    entry.status = "inventory";
    entries(end + 1) = entry;
    return;
end

if ~isstruct(value) || ~isscalar(value)
    return;
end
names = fieldnames(value);
for idx = 1:numel(names)
    field = names{idx};
    if isempty(prefix)
        childPrefix = field;
    else
        childPrefix = [prefix '.' field];
    end
    entries = appendPlatformLeaves(entries, value.(field), childPrefix);
end
end

function token = firstToken(value)
parts = split(string(value), '.');
token = parts(1);
end

function entry = entryTemplate()
entry = struct( ...
    'canonicalName', "", ...
    'displayName', "", ...
    'domain', "", ...
    'unit', "", ...
    'defaultValue', [], ...
    'minimum', [], ...
    'maximum', [], ...
    'source', "", ...
    'modelWorkspaceVariable', "", ...
    'blockParameter', "", ...
    'profileField', "", ...
    'tunableClass', "", ...
    'requiresCompile', "", ...
    'validationLevel', "", ...
    'riskLevel', "", ...
    'description', "", ...
    'status', "");
end
