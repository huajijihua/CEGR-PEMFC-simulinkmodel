    'stable');
result.missingA8Classifications = setdiff(requiredA8Params, ...
    unique(paramNames), 'stable');
result.allA8Classified = isempty(result.missingA8Classifications);
result.profileCandidates = governanceParametersWithTag(items, "进入profile");
result.adjustCandidates = governanceParametersWithTag(items, "建议调整");
result.placeholderParameters = governanceParametersWithTag(items, "仅占位");
result.evidenceGapParameters = governanceParametersWithTag(items, "证据不足");
result.passed = result.tagsOk && result.presentOk && result.allA8Classified;
end

function params = governanceParametersWithTag(items, tag)
mask = [items.tag] == string(tag);
if any(mask)
    params = [items(mask).parameter];
else
    params = strings(1, 0);
end
end

