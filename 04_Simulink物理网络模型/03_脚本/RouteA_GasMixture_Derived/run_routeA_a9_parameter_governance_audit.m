function result = runSteadyCase(model, modelFile, nominalEnvelope, ...
    caseName, restrictionArea)
result = emptySteadyResult();
result.name = string(caseName);
result.targetPowerKW = nominalEnvelope.powerKW;
result.theoreticalHeatRejectKW = nominalEnvelope.heatRejectKW;
result.targetCurrentA = nominalEnvelope.currentA;
result.targetCurrentDensityAcm2 = nominalEnvelope.currentDensityAcm2;
result.restrictionArea = string(restrictionArea);
try
    resetModelFromDisk(model, modelFile);
    refreshModelWorkspace(model);
    paths = routeA_block_paths(model);
    markAuditSignals(paths);
    simIn = Simulink.SimulationInput(model);
    simIn = simIn.setModelParameter( ...
        'StopTime', '30', ...
        'SignalLogging', 'on', ...
        'SignalLoggingName', 'logsout', ...
        'ReturnWorkspaceOutputs', 'on', ...
        'SimscapeLogType', 'all');
    simIn = simIn.setVariable('drive_cycle_time', [0; 5; 30], ...
        'Workspace', model);
    simIn = simIn.setVariable('drive_cycle_power', ...
        [0; nominalEnvelope.powerKW; nominalEnvelope.powerKW], ...
        'Workspace', model);
    simIn = simIn.setVariable('routeA_cathode_humidifier_gain', 1);
    simIn = simIn.setBlockParameter(paths.egrValve, ...
        'restriction_area', char(restrictionArea));
    simOut = sim(simIn);
    result.passed = true;
    result = collectSteadyResult(simOut, result, model);
    result.pressureChainOk = checkPressureChain(result);
    result.kpiFiniteOk = all(isfinite([result.egrRatioCompIn, ...
        result.egrSplitRatioOut, result.rhCaIn, result.rhCaOut, ...
        result.mWaterSep, result.targetPowerKW, ...
        result.theoreticalHeatRejectKW]));
    result.kpiNonnegativeOk = all([result.egrRatioCompIn, ...
        result.egrSplitRatioOut, result.rhCaIn, result.rhCaOut, ...
        result.mWaterSep, result.targetPowerKW, ...
        result.theoreticalHeatRejectKW] >= 0);
catch ME
    result.passed = false;
    result.errorId = string(ME.identifier);
    result.errorMessage = firstLine(string(ME.message));
end
resetModelFromDisk(model, modelFile);
end

