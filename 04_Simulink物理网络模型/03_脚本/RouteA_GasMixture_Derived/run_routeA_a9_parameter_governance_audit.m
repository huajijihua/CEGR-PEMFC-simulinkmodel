    "intercooler_dp_nominal", ...
    "intercooler_mdot_nominal", ...
    "separator_condensation_enabled", ...
    "separator_l2_efficiency", ...
    "cathode_separator_D", ...
    "cathode_separator_length", ...
    "cathode_separator_area", ...
    "cathode_separator_dp_nominal", ...
