function result = auditParameterIsolation(model, modelDir)
mw = get_param(model, 'ModelWorkspace');
parameterFile = fullfile(modelDir, ...
    'PEMFuelCellSystemWithACustomLibraryParameters.m');
txt = string(fileread(parameterFile));

result = struct();
result.parameterFile = string(parameterFile);
result.layer = string(getWorkspaceValue(mw, 'routeA_parameter_layer', ""));
result.externalCaseEnabled = logical(getWorkspaceValue(mw, ...
    'routeA_external_case_enabled', true));
result.defaultScriptReadsTables = contains(txt, "readtable(") || ...
    contains(txt, ".csv") || contains(txt, ".xlsx") || ...
    contains(txt, ".xls");
result.defaultScriptReadsOldBench = contains(txt, ...
    "combined_noegr_cegr_fit_points.csv") || ...
    contains(txt, "simplified_") || contains(txt, "init_testbench_10kw");
result.layerOk = result.layer == "platform_default";
result.externalCaseFlagOk = ~result.externalCaseEnabled;
result.noDefaultFileDataLoad = ~result.defaultScriptReadsTables && ...
    ~result.defaultScriptReadsOldBench;
result.externalCaseGuard = auditExternalCaseGuard(model);
result.passed = result.layerOk && result.externalCaseFlagOk && ...
    result.noDefaultFileDataLoad && result.externalCaseGuard.passed;
end

function result = auditExternalCaseGuard(model)
result = struct();
result.disabledByDefault = false;
result.errorId = "";
result.errorMessage = "";
try
    run('run_routeA_a7_bench_sanity.m');
    result.errorId = "NO_ERROR";
    result.errorMessage = "external_case script did not reject default run";
catch ME
    result.errorId = string(ME.identifier);
    result.errorMessage = firstLine(string(ME.message));
    result.disabledByDefault = result.errorId == "RouteA:ExternalCase:Disabled";
end
resetModelFromDisk(model, [model '.slx']);
refreshModelWorkspace(model);
result.passed = result.disabledByDefault;
end

function result = auditFormulaEnvelope(model)
mw = get_param(model, 'ModelWorkspace');
params = readFormulaParameters(mw);
cases = [ ...
    envelopeCase("low_load_cegr", 0.20, 0.78), ...
    envelopeCase("nominal_50kW", 0.70, 0.65), ...
    envelopeCase("high_power_envelope", 1.20, 0.58)];

for k = 1:numel(cases)
    cases(k) = computeEnvelopeCase(cases(k), params);
end

result = struct();
result.parameters = params;
result.cases = cases;
result.lowLoadCegr = cases(1);
result.nominal50kW = cases(2);
result.highPowerEnvelope = cases(3);
result.nominalPowerOk = cases(2).powerKW >= 45 && cases(2).powerKW <= 60;
result.highPowerMarginOk = cases(3).compressorMargin >= 2;
result.nominalAirMarginOk = cases(2).compressorMargin >= 2;
result.pressureDropFiniteOk = all(isfinite([ ...
    cases.intercoolerDpKPa, cases.cathodeSeparatorDpKPa, ...
    cases.anodeSeparatorDpKPa]));
result.finiteOk = all(isfinite([ ...
    cases.powerKW, cases.h2KgS, cases.o2KgS, cases.waterKgS, ...
    cases.airKgS, cases.heatRejectKW, cases.cathodeVelocityMS, ...
    cases.anodeHydrogenVelocityMS, cases.compressorMargin]));
result.a9SecondRoundThresholds = struct( ...
    'maxNominalAnodeHydrogenVelocityMS', 40, ...
    'minNominalCathodeSeparatorFlowMargin', 1.5, ...
    'minHighPowerCathodeSeparatorFlowMargin', 1.0, ...
    'maxCegrValveToPipeArea', 0.05);
result.nominalAnodeVelocityOk = cases(2).anodeHydrogenVelocityMS < ...
    result.a9SecondRoundThresholds.maxNominalAnodeHydrogenVelocityMS;
result.nominalCathodeSeparatorMarginOk = ...
    cases(2).cathodeSeparatorFlowMargin >= ...
    result.a9SecondRoundThresholds.minNominalCathodeSeparatorFlowMargin;
result.highPowerCathodeSeparatorMarginOk = ...
    cases(3).cathodeSeparatorFlowMargin >= ...
    result.a9SecondRoundThresholds.minHighPowerCathodeSeparatorFlowMargin;
result.cegrMaxValveFractionOk = params.cegrMaxValveToPipeArea <= ...
    result.a9SecondRoundThresholds.maxCegrValveToPipeArea && ...
    params.cegrMaxValveToPipeArea > params.cegrLowValveToPipeArea;
result.warnings = strings(0, 1);
if cases(2).anodeHydrogenVelocityMS > 100
    result.warnings(end + 1, 1) = "anode_tube_velocity_high_at_nominal";
end
if cases(2).cathodeSeparatorFlowMargin < 1.2
    result.warnings(end + 1, 1) = "cathode_separator_nominal_flow_close_to_air_demand";
end
if params.cegrMaxValveToPipeArea > 0.5
    result.warnings(end + 1, 1) = "cegr_max_valve_area_is_broad_upper_bound";
end
result.passed = result.nominalPowerOk && result.highPowerMarginOk && ...
    result.nominalAirMarginOk && result.pressureDropFiniteOk && ...
    result.finiteOk && result.nominalAnodeVelocityOk && ...
    result.nominalCathodeSeparatorMarginOk && ...
    result.highPowerCathodeSeparatorMarginOk && ...
    result.cegrMaxValveFractionOk;
end

