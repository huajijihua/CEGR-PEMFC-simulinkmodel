function c = envelopeCase(name, currentDensityAcm2, cellVoltageV)
c = struct();
c.name = string(name);
c.currentDensityAcm2 = currentDensityAcm2;
c.cellVoltageV = cellVoltageV;
c.currentA = NaN;
c.powerKW = NaN;
c.h2KgS = NaN;
c.o2KgS = NaN;
c.waterKgS = NaN;
c.airKgS = NaN;
c.heatRejectKW = NaN;
c.coolantRequiredKgS = NaN;
c.cathodeVelocityMS = NaN;
c.anodeHydrogenVelocityMS = NaN;
c.compressorMargin = NaN;
c.intercoolerDpKPa = NaN;
c.cathodeSeparatorDpKPa = NaN;
c.anodeSeparatorDpKPa = NaN;
c.cathodeSeparatorFlowMargin = NaN;
c.anodeSeparatorFlowMargin = NaN;
end

function c = computeEnvelopeCase(c, p)
c.currentA = p.stackAreaCm2 * c.currentDensityAcm2;
c.powerKW = p.stackNumCells * c.currentA * c.cellVoltageV / 1000;
c.h2KgS = p.stackNumCells * c.currentA * p.mH2 / (2 * p.faraday);
c.o2KgS = p.stackNumCells * c.currentA * p.mO2 / (4 * p.faraday);
c.waterKgS = p.stackNumCells * c.currentA * p.mH2O / (2 * p.faraday);
c.airKgS = p.airStoich * c.o2KgS / p.airO2MassFraction;
c.heatRejectKW = c.powerKW * (1 / p.electricalEfficiencyForHeat - 1);
c.coolantRequiredKgS = c.heatRejectKW * 1000 / ...
    (p.coolantCp * p.coolantDeltaT);
c.cathodeVelocityMS = safeDivide(c.airKgS, ...
    p.rhoAir * pi * p.cathodeTubeD^2 / 4);
c.anodeHydrogenVelocityMS = safeDivide(c.h2KgS, ...
    p.rhoH2LowPressure * pi * p.anodeTubeD^2 / 4);
c.compressorMargin = safeDivide(p.maxCompressorMdotKgS, c.airKgS);
c.intercoolerDpKPa = scaledPressureDropKPa( ...
    p.intercoolerDpNominalMPa, c.airKgS, p.intercoolerMdotNominalKgS);
c.cathodeSeparatorDpKPa = scaledPressureDropKPa( ...
    p.cathodeSeparatorDpNominalMPa, c.airKgS, ...
    p.cathodeSeparatorMdotNominalKgS);
c.anodeSeparatorDpKPa = scaledPressureDropKPa( ...
    p.anodeSeparatorDpNominalMPa, c.h2KgS, ...
    p.anodeSeparatorMdotNominalKgS);
c.cathodeSeparatorFlowMargin = safeDivide( ...
    p.cathodeSeparatorMdotNominalKgS, c.airKgS);
c.anodeSeparatorFlowMargin = safeDivide( ...
    p.anodeSeparatorMdotNominalKgS, c.h2KgS);
end

