    'canonicalName', "", ...
    'displayName', "", ...
    'domain', "", ...
    'signalName', "", ...
    'unit', "", ...
    'sourceType', "", ...
    'yOrZ', "", ...
    'required', false, ...
    'shape', "", ...
    'producerPath', "", ...
    'auditUse', "", ...
    'status', "", ...
    'trustStatus', "pending_audit", ...
    'panelExposure', "", ...
    'resultField', "", ...
    'verificationGate', "", ...
    'unsupportedReason', "");
end
