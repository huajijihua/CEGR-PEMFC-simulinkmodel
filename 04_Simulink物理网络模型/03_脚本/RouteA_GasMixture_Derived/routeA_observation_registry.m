    function add(canonicalName, displayName, domain, signalName, unit, ...
            sourceType, yOrZ, required, shape, producerPath, auditUse, status)
        entry = entryTemplate();
        entry.canonicalName = string(canonicalName);
        entry.displayName = string(displayName);
        entry.domain = string(domain);
        entry.signalName = string(signalName);
        entry.unit = string(unit);
        entry.sourceType = string(sourceType);
        entry.yOrZ = string(yOrZ);
        entry.required = logical(required);
        entry.shape = string(shape);
        entry.producerPath = string(producerPath);
        entry.auditUse = string(auditUse);
        entry.status = string(status);
        entry = applyPanelMetadata(entry);
        entries(end + 1) = entry;
    end
end

function entry = applyPanelMetadata(entry)
% Structural status is intentionally separate from panel trust. Existing
% signals may be wired and logged, but remain pending until a real
% baseline/perturbation audit proves their physical meaning.
if any(entry.status == ["verified", "optional", "instrumented"])
    entry.panelExposure = "result";
    entry.resultField = entry.canonicalName;
    entry.verificationGate = "behavior_audit_pending";
    entry.unsupportedReason = "";
elseif entry.status == "unresolved"
    entry.panelExposure = "status_only";
    entry.resultField = "";
    entry.verificationGate = "not_observable";
    entry.unsupportedReason = "Signal name or producer path is not resolved in the active model.";
else
    entry.panelExposure = "inventory";
    entry.resultField = "";
    entry.verificationGate = "not_opened";
    entry.unsupportedReason = "Observation status is not active for P1 results.";
end
end

function entry = entryTemplate()
