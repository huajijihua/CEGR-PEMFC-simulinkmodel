end

function thermal = getThermalControls(caseCfg, baseline)
thermal = struct('stackTemperatureSet_C', ...
    baseline.stack_temperature_set_C);
user = getOptionalStruct(caseCfg, 'thermal');
thermal = mergeKnownFields(thermal, user, 'RouteA:ThermalControlField');
end

function baseline = commandBaseline(metadata)
required = {'commandProfileSchema', 'commandProfileFields', ...
    'commandProfileBaseline'};
if ~builtin('all', isfield(metadata, required)) || ...
        ~contains(string(metadata.commandProfileSchema), "_v10")
    error('RouteA:InitialStateCommandProfileMetadata', ...
        ['The selected initial state lacks the v10 runtime-command ', ...
        'baseline metadata. Generate and promote the v10 bundle first.']);
end
fields = string(metadata.commandProfileFields(:).');
values = metadata.commandProfileBaseline;
if ~isnumeric(values) || ~isvector(values) || ...
        numel(fields) ~= 22 || numel(values) ~= numel(fields) || ...
        any(~isfinite(values(:)))
    error('RouteA:InitialStateCommandProfileMetadata', ...
        'The v10 runtime-command baseline has an invalid 22-field schema.');
end
expected = [ ...
    "cathode_source_pressure_MPa_abs", ...
    "cathode_source_temperature_C", ...
    "cathode_source_o2_mole_fraction", ...
    "cathode_source_h2o_mole_fraction", ...
    "air_target_mdot_kg_s", "air_target_oer", "air_direct_command", ...
    "cathode_outlet_pressure_MPa_abs", "cathode_humidifier_rh", ...
    "cathode_humidifier_gain", "cegr_ratio", ...
    "anode_source_pressure_MPa_abs", ...
    "anode_source_temperature_C", "anode_source_h2_mole_fraction", ...
    "anode_inlet_pressure_MPa_abs", "anode_humidifier_rh", ...
    "anode_recirculation_base", ...
    "anode_recirculation_current_gain_A_inv", "anode_purge_enable", ...
    "anode_purge_on_n2_mole_fraction", ...
    "anode_purge_off_n2_mole_fraction", "stack_temperature_set_C"];
if ~builtin('all', fields == expected)
    error('RouteA:InitialStateCommandProfileSchema', ...
        'The v10 runtime-command field order is not the Route A schema.');
end
baseline = cell2struct(num2cell(values(:).'), cellstr(fields), 2);
end

function profile = assembleCommandProfile( ...
    baseline, air, cathode, anode, thermal, cegrSpec, study)
specs = { ...
    'cathode_source_pressure_MPa_abs', 'CathodeSourcePressure', ...
        cathode.sourcePressure_MPa_abs, false; ...
    'cathode_source_temperature_C', 'CathodeSourceTemperature', ...
        cathode.sourceTemperature_C, false; ...
    'cathode_source_o2_mole_fraction', 'CathodeSourceO2', ...
        cathode.freshAirO2MoleFraction, false; ...
    'cathode_source_h2o_mole_fraction', 'CathodeSourceH2O', ...
        cathode.freshAirWaterMoleFraction, false; ...
    'air_target_mdot_kg_s', 'AirTargetMdot', air.targetMdot_kg_s, false; ...
    'air_target_oer', 'AirTargetOer', air.targetOer, false; ...
    'air_direct_command', 'AirDirectCommand', air.directCommand, false; ...
    'cathode_outlet_pressure_MPa_abs', 'CathodeOutletPressure', ...
        cathode.outletPressure_MPa_abs, false; ...
    'cathode_humidifier_rh', 'CathodeHumidifierRH', ...
        cathode.humidifierRelativeHumidity, false; ...
    'cathode_humidifier_gain', 'CathodeHumidifierGain', ...
        cathode.humidifierEnabled, false; ...
    'cegr_ratio', 'CEGR', cegrSpec, false; ...
    'anode_source_pressure_MPa_abs', 'AnodeSourcePressure', ...
        anode.tankPressure_MPa_abs, false; ...
    'anode_source_temperature_C', 'AnodeSourceTemperature', ...
        anode.sourceTemperature_C, false; ...
    'anode_source_h2_mole_fraction', 'AnodeSourceH2', ...
        anode.hydrogenMoleFraction, false; ...
    'anode_inlet_pressure_MPa_abs', 'AnodeInletPressure', ...
        anode.inletPressure_MPa_abs, false; ...
    'anode_humidifier_rh', 'AnodeHumidifierRH', ...
        anode.humidifierRelativeHumidity, false; ...
    'anode_recirculation_base', 'AnodeRecirculationBase', ...
        anode.recirculationBaseCommand, false; ...
    'anode_recirculation_current_gain_A_inv', 'AnodeRecirculationGain', ...
        anode.recirculationCurrentGain_A_inv, false; ...
    'anode_purge_enable', 'AnodePurgeEnable', anode.purgeEnabled, true; ...
    'anode_purge_on_n2_mole_fraction', 'AnodePurgeOnN2', ...
        anode.purgeOnN2MoleFraction, false; ...
    'anode_purge_off_n2_mole_fraction', 'AnodePurgeOffN2', ...
        anode.purgeOffN2MoleFraction, false; ...
    'stack_temperature_set_C', 'StackTemperature', ...
        thermal.stackTemperatureSet_C, false};
count = size(specs, 1);
profiles = cell(count, 1);
time = zeros(0, 1);
for idx = 1:count
    field = specs{idx, 1};
    options = struct( ...
        'duration_s', study.researchDuration_s, ...
        'commandStartOffset_s', study.commandStartOffset_s, ...
        'startupRampDuration_s', study.startupRampDuration_s, ...
        'initialValue', baseline.(field), 'label', string(field));
    if specs{idx, 4}
        options.startupRampDuration_s = 0;
    end
    profiles{idx} = routeA_normalize_electrical_profile( ...
        specs{idx, 3}, specs{idx, 2}, options);
    time = unique([time; profiles{idx}.time_s], 'sorted');
end
value = zeros(numel(time), count);
for idx = 1:count
    value(:, idx) = interp1(profiles{idx}.time_s, profiles{idx}.value, ...
        time, 'linear');
end
validateCommandProfileMatrix(time, value);
profile = struct('schema', "RouteA_Command_Profile_v10", ...
    'fields', string(specs(:, 1)).', 'time_s', time, 'value', value, ...
    'workspaceValue', [time, value], 'individual', {profiles});
end

function validateCommandProfileMatrix(time, value)
if any(~isfinite(time)) || any(~isfinite(value(:))) || any(diff(time) <= 0)
    error('RouteA:CommandProfileFinite', ...
        'The unified runtime-command profile is not finite and ordered.');
end
if any(value(:, 3) + value(:, 4) > 1 + 1e-12)
    error('RouteA:CathodeSourceComposition', ...
        'Cathode O2 and H2O command fractions must sum to no more than one.');
end
if any(value(:, 12) <= value(:, 15))
    error('RouteA:AnodePressureOrder', ...
        'Anode source pressure must exceed the inlet-pressure command.');
end
if any(value(:, 20) <= value(:, 21))
    error('RouteA:AnodePurgeThresholdOrder', ...
        'Anode purge-on threshold must exceed the purge-off threshold.');
end
end

function result = mergeKnownFields(defaults, user, errorId)
result = defaults;
names = fieldnames(user);
for idx = 1:numel(names)
    if ~isfield(result, names{idx})
        error(errorId, 'Unsupported control field: %s.', names{idx});
    end
    result.(names{idx}) = user.(names{idx});
end
end

function controller = getControllerConfig(caseCfg)
controller = struct('Kp_A_V', 1, 'Ki_A_V_s', 0.05, ...
    'currentMin_A', 0, 'currentMax_A', 392);
controller = mergeKnownFields(controller, ...
    getOptionalStruct(caseCfg, 'controller'), ...
    'RouteA:VoltageControlField');
validateattributes(controller.Kp_A_V, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.Ki_A_V_s, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.currentMin_A, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.currentMax_A, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', controller.currentMin_A});
end

function value = getOptionalStruct(parent, fieldName)
if ~isfield(parent, fieldName) || isempty(parent.(fieldName))
    value = struct();
elseif isstruct(parent.(fieldName)) && isscalar(parent.(fieldName))
    value = parent.(fieldName);
else
    error('RouteA:ElectricalBoundaryControlType', ...
        '%s must be a scalar struct.', fieldName);
end
end

function bounds = compressorBounds(mw)
table = mw.getVariable('comp_rpm_TLU');
bounds = [min(table), max(table)];
end
