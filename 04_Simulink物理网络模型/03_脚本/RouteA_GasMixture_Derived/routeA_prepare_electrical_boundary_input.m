end

function [baseline, values] = commandBaseline(model)
mw = get_param(model, 'ModelWorkspace');
fields = string(mw.getVariable('routeA_command_profile_fields'));
values = mw.getVariable('routeA_command_profile_baseline');
schema = routeA_command_profile_schema();
expected = schema.names(:);
if ~isvector(fields) || numel(fields) ~= schema.count || ...
        ~builtin('all', fields(:) == expected)
    error('RouteA:CommandProfileBaselineSchema', ...
        'The model workspace command-profile field order is not the active Route A schema.');
end
if ~isnumeric(values) || ~isvector(values) || ...
        numel(values) ~= schema.count || any(~isfinite(values(:)))
    error('RouteA:CommandProfileBaselineValues', ...
        'The model workspace command-profile baseline has an invalid schema.');
end
values = reshape(double(values), 1, []);
fieldNames = reshape(fields, 1, []);
baseline = cell2struct(num2cell(values), cellstr(fieldNames), 2);
end

function result = mergeKnownFields(defaults, user, errorId)
result = defaults;
names = fieldnames(user);
for idx = 1:numel(names)
    if ~isfield(result, names{idx})
        error(errorId, 'Unsupported control field: %s.', names{idx});
    end
    result.(names{idx}) = user.(names{idx});
end
end

function controller = getControllerConfig(caseCfg)
% PI controller defaults derived from platform parameter file (single source).
pCtrl = routeA_platform_default_parameters().controls;
controller = struct('Kp_A_V', pCtrl.voltage_pi_Kp.value, ...
    'Ki_A_V_s', pCtrl.voltage_pi_Ki.value, ...
    'currentMin_A', pCtrl.voltage_current_min_A.value, ...
    'currentMax_A', pCtrl.voltage_current_max_A.value);
controller = mergeKnownFields(controller, ...
    getOptionalStruct(caseCfg, 'controller'), ...
    'RouteA:VoltageControlField');
validateattributes(controller.Kp_A_V, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.Ki_A_V_s, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.currentMin_A, {'numeric'}, ...
    {'scalar', 'real', 'finite'});
validateattributes(controller.currentMax_A, {'numeric'}, ...
    {'scalar', 'real', 'finite', '>', controller.currentMin_A});
end

function value = getOptionalStruct(parent, fieldName)
if ~isfield(parent, fieldName) || isempty(parent.(fieldName))
    value = struct();
elseif isstruct(parent.(fieldName)) && isscalar(parent.(fieldName))
    value = parent.(fieldName);
else
    error('RouteA:ElectricalBoundaryControlType', ...
        '%s must be a scalar struct.', fieldName);
end
end

function bounds = compressorBounds(mw)
table = mw.getVariable('comp_rpm_TLU');
bounds = [min(table), max(table)];
end
