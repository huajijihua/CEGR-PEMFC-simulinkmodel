    'sourceTemperature_C', baseline.cathode_source_temperature_C, ...
    'freshAirO2MoleFraction', baseline.cathode_source_o2_mole_fraction, ...
    'freshAirWaterMoleFraction', baseline.cathode_source_h2o_mole_fraction, ...
    'outletPressure_MPa_abs', baseline.cathode_outlet_pressure_MPa_abs, ...
    'humidifierRelativeHumidity', baseline.cathode_humidifier_rh, ...
