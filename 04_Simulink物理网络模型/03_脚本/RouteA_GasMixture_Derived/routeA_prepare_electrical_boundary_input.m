    'stackPower_kW', NaN, 'stackTemperature_C', NaN);
end

function controls = buildControlsStruct(air, cathode, anode, thermal, cegrSpec)
% Build a simCase.controls-format struct from the individual routeA config structs.
controls = struct();
controls.cathode = struct( ...
    'airControlMode', air.modeId, ...
    'targetOer', air.targetOer, ...
    'targetMdot_kg_s', air.targetMdot_kg_s, ...
    'directCommand', air.directCommand, ...
    'sourcePressure_MPa_abs', cathode.sourcePressure_MPa_abs, ...
    'sourceTemperature_C', cathode.sourceTemperature_C, ...
    'o2MoleFraction', cathode.freshAirO2MoleFraction, ...
    'h2oMoleFraction', cathode.freshAirWaterMoleFraction, ...
    'outletPressure_MPa_abs', cathode.outletPressure_MPa_abs, ...
    'humidifierRH', cathode.humidifierRelativeHumidity, ...
    'humidifierEnabled', cathode.humidifierEnabled);
controls.cegr = struct('targetRatio', cegrSpec);
controls.anode = struct( ...
    'sourcePressure_MPa_abs', anode.tankPressure_MPa_abs, ...
    'sourceTemperature_C', anode.sourceTemperature_C, ...
    'h2MoleFraction', anode.hydrogenMoleFraction, ...
    'inletPressure_MPa_abs', anode.inletPressure_MPa_abs, ...
    'humidifierRH', anode.humidifierRelativeHumidity, ...
    'recirculationBaseCommand', anode.recirculationBaseCommand, ...
    'recirculationCurrentGain_A_inv', anode.recirculationCurrentGain_A_inv, ...
    'purgeEnabled', anode.purgeEnabled, ...
    'purgeOnN2MoleFraction', anode.purgeOnN2MoleFraction, ...
    'purgeOffN2MoleFraction', anode.purgeOffN2MoleFraction);
controls.thermal = struct( ...
    'stackTemperatureSet_C', thermal.stackTemperatureSet_C);
end

function boundary = getBoundary(caseCfg)
if ~isfield(caseCfg, 'boundary') || ~isstruct(caseCfg.boundary)
    error('RouteA:ElectricalBoundaryMissing', ...
        'Each case must define boundary.type and boundary.profile.');
end
boundary = caseCfg.boundary;
if ~isfield(boundary, 'type')
    error('RouteA:ElectricalBoundaryMissingType', ...
        'Each boundary must define type.');
end
if ~isfield(boundary, 'profile')
    if isfield(boundary, 'value')
        boundary.profile = boundary.value;
    else
        error('RouteA:ElectricalBoundaryMissingProfile', ...
            'Each boundary must define profile.');
    end
end
end

function value = getCegrProfile(caseCfg, baseline)
if ~isfield(caseCfg, 'cegr') || isempty(caseCfg.cegr)
    value = baseline.cegr_ratio;
    return;
end
cegr = caseCfg.cegr;
if isnumeric(cegr)
    value = cegr;
elseif isstruct(cegr) && isfield(cegr, 'profile')
    value = cegr.profile;
elseif isstruct(cegr) && isfield(cegr, 'time_s') && ...
        isfield(cegr, 'value')
    value = cegr;
elseif isstruct(cegr) && isfield(cegr, 'targetRatio')
    value = cegr.targetRatio;
else
    value = cegr;
end
end

function air = getAirConfig(caseCfg, baseline)
air = struct('modeId', 2, ...
    'targetOer', baseline.air_target_oer, ...
    'targetMdot_kg_s', baseline.air_target_mdot_kg_s, ...
    'directCommand', baseline.air_direct_command);
air = mergeKnownFields(air, getOptionalStruct(caseCfg, 'air'), ...
    'RouteA:AirControlField');
validateattributes(air.modeId, {'numeric'}, {'scalar', 'integer', '>=', 1, '<=', 3});
end

