function gaps = buildGapTable(passiveDiagnostics, cfg)
name = [ ...
    "compressor_efficiency_and_shaft_power"; ...
    "compressor_pressure_ratio_coverage"; ...
    "anode_lambda_purge_and_recirculation_capacity"; ...
    "water_separator_efficiency"; ...
    "cooling_pump_capacity_and_control"; ...
    "radiator_UA_and_airflow_capacity"; ...
    "passive_cegr_pressure_and_area_capacity"];
classification = [ ...
    "L2_pending"; "unobservable"; "unobservable"; "L2_pending"; ...
    "unobservable"; "unobservable"; "verified_or_blocking"];
critical = [false; false; false; false; false; false; true];
detail = [ ...
    "Current compressor is a flow-source/map interface, not a mechanical efficiency or surge model."; ...
    "The current audit records flow and rpm; compressor pressure-ratio coverage remains an L2 observability gap."; ...
    "Phase 1 calculates stoichiometric hydrogen demand only; no anode lambda or purge proof is claimed."; ...
    "SeparatorOrCondensation is an L2 saturation-excess estimator with no component efficiency evidence."; ...
    "The cooling pump is a controlled mass-flow source; no flow-capacity map or electric-power evidence is available."; ...
    "Radiator geometry exists, but UA, fan airflow, and independent heat-rejection evidence are absent."; ...
    "Passive cEGR requires positive valve pressure drop, unsaturated area, and passing existing full-case tracking."];
status = repmat("pending", numel(name), 1);
status(1:end-1) = "deferred";
if builtin('all', [passiveDiagnostics.passed])
    status(end) = "verified";
else
    status(end) = "blocking";
end

gaps = table(name, classification, critical, status, detail);
if cfg.parameterLayer ~= "platform_default" || cfg.externalCaseEnabled
    error('RouteA:Phase1ParameterBoundary', ...
        'The audit must not continue outside platform_default.');
end
end

function summary = buildSummary(study, reactionLedger, registry, diagnostics, gaps)
matrixPassed = study.passed;
reactionFinite = builtin('all', builtin('all', ...
    isfinite(reactionLedger{:, 2:end})));
registryComplete = builtin('all', strlength(registry.name) > 0) && ...
    builtin('all', strlength(registry.unit) > 0) && ...
    builtin('all', strlength(registry.status) > 0);
passivePassed = builtin('all', [diagnostics.passed]);
blockingGaps = sum(gaps.critical & gaps.status == "blocking");
auditComplete = matrixPassed && reactionFinite && registryComplete && passivePassed;
engineeringMatchReady = auditComplete && blockingGaps == 0;
summary = table(matrixPassed, reactionFinite, registryComplete, passivePassed, ...
    blockingGaps, auditComplete, engineeringMatchReady);
end

function displayAuditSummary(audit)
fprintf('\nRoute A Phase 1 matching and interface audit\n');
