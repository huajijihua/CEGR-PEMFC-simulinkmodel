function load = loadDefinition(id, currentDensity, referenceVoltage, targetOer)
load = struct('id', string(id), 'currentDensity_A_cm2', currentDensity, ...
    'referenceVoltage_V', referenceVoltage, 'targetOer', targetOer);
end

function verifyPlatformDefault(cfg)
if cfg.parameterLayer ~= "platform_default" || cfg.externalCaseEnabled
    error('RouteA:Phase1ParameterBoundary', ...
        ['Phase 1 requires platform_default with external_case disabled. ', ...
        'No historical bench or product data may enter this audit.']);
end
end

function study = loadOrRunFullcaseStudy(model)
hasExistingStudy = evalin('base', ...
    'exist(''routeA_fullcase_study'', ''var'') == 1');
if hasExistingStudy
    candidate = evalin('base', 'routeA_fullcase_study');
    if isReusableFullcaseStudy(candidate, model)
        study = candidate;
        fprintf(['Reusing the existing Route A nine-case study from the ', ...
            'base workspace.\n']);
        return;
    end
end

run_routeA_fullcase_study;
study = evalin('base', 'routeA_fullcase_study');
if ~isReusableFullcaseStudy(study, model)
    error('RouteA:Phase1InvalidFullcaseStudy', ...
        'The full-case runner did not return the required nine-case matrix.');
end
end

function reusable = isReusableFullcaseStudy(study, model)
requiredCaseIds = ["nominal_noCEGR", "nominal_withCEGR_010", ...
    "nominal_withCEGR_030", "low_noCEGR", "low_withCEGR_010", ...
    "low_withCEGR_030", "high_noCEGR", "high_withCEGR_010", ...
    "high_withCEGR_030"];
reusable = isstruct(study) && isfield(study, 'model') && ...
    isfield(study, 'stopTime_s') && isfield(study, 'results') && ...
    isequal(string(study.model), string(model)) && ...
    isequal(study.stopTime_s, 120) && numel(study.results) == numel(requiredCaseIds);
if ~reusable
    return;
end

actualCaseIds = string({study.results.caseId});
reusable = isequal(sort(actualCaseIds(:)), sort(requiredCaseIds(:)));
end

function ledger = buildReactionLedger(cfg)
airMolarMass = ambientAirMolarMass(cfg);
oxygenMassFraction = cfg.envYO2 * cfg.molarMassO2KgMol / airMolarMass;
if ~isfinite(oxygenMassFraction) || oxygenMassFraction <= 0
    error('RouteA:Phase1InvalidAmbientComposition', ...
        'Ambient oxygen mass fraction cannot be determined.');
end

nLoads = numel(cfg.loads);
loadId = strings(nLoads, 1);
currentDensity = zeros(nLoads, 1);
stackCurrent = zeros(nLoads, 1);
referenceVoltage = zeros(nLoads, 1);
targetOer = zeros(nLoads, 1);
targetPower = zeros(nLoads, 1);
h2Mdot = zeros(nLoads, 1);
o2Mdot = zeros(nLoads, 1);
waterMdot = zeros(nLoads, 1);
freshAirMdot = zeros(nLoads, 1);
compressorMdotNoCegr = zeros(nLoads, 1);
compressorMdot010 = zeros(nLoads, 1);
compressorMdot030 = zeros(nLoads, 1);
thermalPower = zeros(nLoads, 1);
electricalEfficiencyLhv = zeros(nLoads, 1);

for idx = 1:nLoads
    load = cfg.loads(idx);
    current = load.currentDensity_A_cm2 * cfg.stackAreaCm2;
    h2MolS = cfg.stackCells * current / (2 * cfg.faradayCmol);
    o2MolS = cfg.stackCells * current / (4 * cfg.faradayCmol);
    waterMolS = h2MolS;
    powerW = cfg.stackCells * current * load.referenceVoltage_V;
    freshAir = load.targetOer * o2MolS * cfg.molarMassO2KgMol / ...
        oxygenMassFraction;

    loadId(idx) = load.id;
    currentDensity(idx) = load.currentDensity_A_cm2;
    stackCurrent(idx) = current;
    referenceVoltage(idx) = load.referenceVoltage_V;
    targetOer(idx) = load.targetOer;
    targetPower(idx) = powerW / 1000;
    h2Mdot(idx) = h2MolS * cfg.molarMassH2KgMol;
    o2Mdot(idx) = o2MolS * cfg.molarMassO2KgMol;
    waterMdot(idx) = waterMolS * cfg.molarMassH2OKgMol;
    freshAirMdot(idx) = freshAir;
    compressorMdotNoCegr(idx) = freshAir;
    compressorMdot010(idx) = freshAir / (1 - 0.10);
    compressorMdot030(idx) = freshAir / (1 - 0.30);
    thermalPower(idx) = cfg.stackCells * current * ...
        (cfg.thermoneutralVoltageV - load.referenceVoltage_V) / 1000;
    electricalEfficiencyLhv(idx) = powerW / ...
        (h2Mdot(idx) * cfg.hydrogenLhvJkg);
end

ledger = table(loadId, currentDensity, stackCurrent, referenceVoltage, ...
    targetOer, targetPower, h2Mdot, o2Mdot, waterMdot, freshAirMdot, ...
    compressorMdotNoCegr, compressorMdot010, compressorMdot030, ...
    thermalPower, electricalEfficiencyLhv, ...
    'VariableNames', {'loadId', 'currentDensity_A_cm2', 'stackCurrent_A', ...
    'referenceVoltage_V', 'targetOer', 'targetPower_kW', 'h2Demand_kg_s', ...
    'o2Demand_kg_s', 'waterGeneration_kg_s', 'freshAirDemand_kg_s', ...
    'compressorInletScreen_noCEGR_kg_s', ...
    'compressorInletScreen_010_kg_s', ...
    'compressorInletScreen_030_kg_s', 'stackThermalDemand_kW', ...
    'electricalEfficiency_LHV'});
end

function molarMass = ambientAirMolarMass(cfg)
yN2 = 1 - cfg.envYO2 - cfg.envYH2O;
if yN2 < 0
    error('RouteA:Phase1InvalidAmbientComposition', ...
        'Ambient mole fractions sum to more than one.');
end
molarMass = cfg.envYO2 * cfg.molarMassO2KgMol + ...
    yN2 * cfg.molarMassN2KgMol + cfg.envYH2O * cfg.molarMassH2OKgMol;
end

function ledger = buildCoolingLedger(reactionLedger, cfg)
nRows = height(reactionLedger) * numel(cfg.coolantDeltaTK);
loadId = strings(nRows, 1);
deltaT = zeros(nRows, 1);
thermalDemand = zeros(nRows, 1);
coolantMdot = zeros(nRows, 1);
row = 0;
for iLoad = 1:height(reactionLedger)
    for iDeltaT = 1:numel(cfg.coolantDeltaTK)
        row = row + 1;
        loadId(row) = reactionLedger.loadId(iLoad);
        deltaT(row) = cfg.coolantDeltaTK(iDeltaT);
        thermalDemand(row) = reactionLedger.stackThermalDemand_kW(iLoad);
        coolantMdot(row) = thermalDemand(row) * 1000 / ...
            (cfg.coolantCpJkgK * deltaT(row));
    end
end
ledger = table(loadId, deltaT, thermalDemand, coolantMdot, ...
    'VariableNames', {'loadId', 'coolantDeltaT_K', ...
    'stackThermalDemand_kW', 'requiredCoolantMdot_kg_s'});
end

function diagnostics = runPassiveCegrDiagnostics(study, cfg, model, modelFile)
diagnostics = repmat(emptyPassiveDiagnostic(), numel(cfg.egrTargets), 1);
for idx = 1:numel(cfg.egrTargets)
    target = cfg.egrTargets(idx);
    caseId = "nominal_withCEGR_" + compose('%03d', round(target * 100));
    result = findCaseResult(study.results, caseId);
    diagnostics(idx) = runPassiveCase(result, cfg, model, modelFile);
end
end

function result = findCaseResult(results, caseId)
ids = string({results.caseId});
index = find(ids == caseId, 1);
if isempty(index)
    error('RouteA:Phase1MissingFullcaseResult', ...
        'The full-case study did not return %s.', caseId);
end
result = results(index);
end

function diagnostic = emptyPassiveDiagnostic()
diagnostic = struct('caseId', "", 'targetEgrRatio', NaN, ...
    'targetOer', NaN, 'targetPowerKW', NaN, 'fullcasePassed', false, ...
    'simCompleted', false, 'actualEgrRatio', NaN, 'areaFractionTailMin', NaN, ...
    'areaFractionTailMax', NaN, 'pressureUpstreamTailMPa', NaN, ...
    'pressureDownstreamTailMPa', NaN, 'pressureDeltaTailMPa', NaN, ...
    'finiteOk', false, 'areaWithinBounds', false, 'notSaturated', false, ...
    'forwardPressureDrop', false, 'passed', false, 'errorId', "", ...
    'errorMessage', "");
end

function diagnostic = runPassiveCase(caseResult, cfg, model, modelFile)
diagnostic = emptyPassiveDiagnostic();
diagnostic.caseId = string(caseResult.caseId);
diagnostic.targetEgrRatio = caseResult.targetEgrRatio;
diagnostic.targetOer = caseResult.targetOer;
diagnostic.targetPowerKW = caseResult.targetPowerKW;
diagnostic.fullcasePassed = caseResult.passed;

try
    resetModelFromDisk(model, modelFile);
    mw = get_param(model, 'ModelWorkspace');
    if strcmp(mw.DataSource, 'MATLAB File')
        mw.reload;
    end
    mw.assignin('routeA_cegr_enabled', true);
    mw.assignin('routeA_cegr_valve_mode_id', ...
        double(caseResult.targetEgrRatio > 0));
    set_param(model, 'SimulationCommand', 'update');

    paths = routeA_block_paths(model);
    markDiagnosticSignals(paths);
    in = Simulink.SimulationInput(model);
    in = in.setModelParameter('StopTime', sprintf('%.16g', cfg.stopTimeS), ...
        'SignalLogging', 'on', 'SignalLoggingName', 'logsout', ...
        'ReturnWorkspaceOutputs', 'on', 'SimscapeLogType', 'all');
    in = in.setVariable('drive_cycle_time', [0; 0.5; cfg.stopTimeS], ...
        'Workspace', model);
    in = in.setVariable('drive_cycle_power', ...
        [0; caseResult.targetPowerKW; caseResult.targetPowerKW], ...
        'Workspace', model);
    in = in.setVariable('routeA_air_control_mode_id', 2, ...
        'Workspace', model);
    in = in.setVariable('routeA_target_oer', caseResult.targetOer, ...
        'Workspace', model);
    in = in.setVariable('routeA_egr_control_mode_id', 1, ...
        'Workspace', model);
    in = in.setVariable('routeA_cegr_valve_mode_id', ...
        double(caseResult.targetEgrRatio > 0), 'Workspace', model);
    in = in.setVariable('routeA_target_egr_ratio_comp_in', ...
        caseResult.targetEgrRatio, 'Workspace', model);
    out = sim(in);
    diagnostic.simCompleted = true;

    egr = loggedTimeseries(out, 'routeA_egr_ratio_comp_in');
    area = loggedTimeseries(out, 'routeA_egr_valve_area_cmd');
    pUp = loggedTimeseries(out, 'routeA_p_egr_valve_up');
    pDown = loggedTimeseries(out, 'routeA_p_egr_valve_down');
    diagnostic.actualEgrRatio = tailMean(egr, cfg.tailSeconds);
    diagnostic.areaFractionTailMin = tailMinimum(area, cfg.tailSeconds) / ...
        cfg.cegrValveMaxArea;
    diagnostic.areaFractionTailMax = tailMaximum(area, cfg.tailSeconds) / ...
        cfg.cegrValveMaxArea;
    diagnostic.pressureUpstreamTailMPa = tailMean(pUp, cfg.tailSeconds) * 1e-6;
    diagnostic.pressureDownstreamTailMPa = tailMean(pDown, cfg.tailSeconds) * 1e-6;
    diagnostic.pressureDeltaTailMPa = diagnostic.pressureUpstreamTailMPa - ...
        diagnostic.pressureDownstreamTailMPa;
    values = [diagnostic.actualEgrRatio, diagnostic.areaFractionTailMin, ...
        diagnostic.areaFractionTailMax, diagnostic.pressureUpstreamTailMPa, ...
        diagnostic.pressureDownstreamTailMPa, diagnostic.pressureDeltaTailMPa];
    diagnostic.finiteOk = builtin('all', isfinite(values));
    diagnostic.areaWithinBounds = diagnostic.areaFractionTailMin >= 0 && ...
        diagnostic.areaFractionTailMax <= 1 + 1e-9;
    diagnostic.notSaturated = diagnostic.areaFractionTailMax < 1 - 1e-6;
    diagnostic.forwardPressureDrop = diagnostic.pressureDeltaTailMPa > 0;
    diagnostic.passed = diagnostic.fullcasePassed && diagnostic.simCompleted && ...
        diagnostic.finiteOk && diagnostic.areaWithinBounds && ...
        diagnostic.notSaturated && diagnostic.forwardPressureDrop;
catch ME
    diagnostic.errorId = string(ME.identifier);
    diagnostic.errorMessage = firstLine(string(ME.message));
end
resetModelFromDisk(model, modelFile);
end

function markDiagnosticSignals(paths)
markSignalFromBlockOutput(paths.fcu, 1, 'routeA_egr_valve_area_cmd');
markSignalFromBlockOutput(paths.fcu, 4, 'routeA_egr_ratio_comp_in');
markSignalFromBlockOutput(paths.egrValveUpPConverter, 1, ...
    'routeA_p_egr_valve_up');
markSignalFromBlockOutput(paths.egrValveDownPConverter, 1, ...
    'routeA_p_egr_valve_down');
end

function markSignalFromBlockOutput(blockPath, portNumber, signalName)
if getSimulinkBlockHandle(blockPath) == -1
    error('RouteA:Phase1MissingSignalSource', ...
        'Signal source block is not available: %s.', blockPath);
end
portHandles = get_param(blockPath, 'PortHandles');
if numel(portHandles.Outport) < portNumber
    error('RouteA:Phase1MissingSignalPort', ...
        'Signal source port is not available: %s.', blockPath);
end
portHandle = portHandles.Outport(portNumber);
lineHandle = get_param(portHandle, 'Line');
if lineHandle == -1
    error('RouteA:Phase1UnconnectedSignal', ...
        'Signal source port is not connected: %s.', blockPath);
end
set_param(lineHandle, 'Name', signalName);
set_param(portHandle, 'DataLogging', 'on');
set_param(portHandle, 'DataLoggingNameMode', 'Custom', ...
    'DataLoggingName', signalName);
end

function signal = loggedTimeseries(out, name)
element = out.logsout.get(name);
if isempty(element) || isempty(element.Values)
    error('RouteA:Phase1UnobservableSignal', ...
        'The required logged signal is unavailable: %s.', name);
end
signal = element.Values;
end

function value = tailMean(signal, seconds)
data = tailData(signal, seconds);
value = mean(data, 'all');
end

function value = tailMinimum(signal, seconds)
data = tailData(signal, seconds);
value = min(data, [], 'all');
end

function value = tailMaximum(signal, seconds)
data = tailData(signal, seconds);
value = max(data, [], 'all');
end

function data = tailData(signal, seconds)
time = signal.Time(:);
mask = time >= time(end) - seconds;
data = signal.Data(mask, :);
if isempty(data)
    error('RouteA:Phase1EmptyTail', 'No samples are available in the tail window.');
end
end

