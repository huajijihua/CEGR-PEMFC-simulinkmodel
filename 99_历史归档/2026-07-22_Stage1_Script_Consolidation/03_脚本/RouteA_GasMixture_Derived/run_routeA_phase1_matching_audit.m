function registry = applyPassiveCegrDiagnosticStatus(registry, diagnostics)
names = ["cegr_valve_max_area", "routeA_egr_control_Kp_area", ...
    "routeA_egr_control_Ki_area"];
indices = ismember(registry.name, names);
if builtin('all', [diagnostics.passed])
    registry.status(indices) = "verified_nominal";
else
    registry.status(indices) = "blocking";
end
end

